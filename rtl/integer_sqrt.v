// Floor(sqrt(x)) by trial bits, one candidate square per cycle.

// =====================================================================
// integer_sqrt: complete controller + datapath + top in one Verilog file.
// Pulse start while busy=0. Inputs are latched on the accepting edge.
// Reset and port conventions are preserved from the original module.
// Packed array lane i occupies bits [i*W +: W], unless stated otherwise.
// =====================================================================
// control[0]: value <= x;
// control[1]: root <= 0;
// control[2]: bit_index <= (W - 1) / 2;
// control[3]: root <= candidate;
// control[4]: result <= (square <= value)? candidate : root;
// control[5]: bit_index <= bit_index - 1;

// ---------------- CONTROLLER ----------------
module integer_sqrt_controller #
(
  parameter W = 32
)
(
  input clk,
  input rst_n,
  input start,
  input [1:0] status,
  output reg [5:0] control,
  output reg busy,
  output reg done);


reg next_busy;
reg next_done;

// FSM state/handshake registers; all data writes are control strobes.

always @(posedge clk) if(!rst_n) begin
  busy <= 0;
  done <= 0;
end else begin
  busy <= next_busy;
  done <= next_done;
end


always @(*) begin
  next_busy = busy;
  next_done = done;
  control = 0;
  begin
    next_done = 0;
    if(start && !busy) begin
      control[0] = 1'b1;
      control[1] = 1'b1;
      control[2] = 1'b1;
      next_busy = 1;
    end else if(busy) begin
      if(status[0]) control[3] = 1'b1;
      if(status[1]) begin
        control[4] = 1'b1;
        next_busy = 0;
        next_done = 1;
      end else control[5] = 1'b1;
    end
  end
end

endmodule

// ---------------- DATAPATH ----------------
module integer_sqrt_datapath #
(
  parameter W = 32
)
(
  input clk,
  input rst_n,
  input [W-1:0] x,
  input [5:0] control,
  output [1:0] status,
  output reg [W-1:0] result);
reg [W-1:0] value;
reg [W-1:0] root;
integer bit_index;
wire [W-1:0] candidate;
assign candidate = root | ({ { W - 1{ 1'b0 } }, 1'b1 } << bit_index);
wire [2*W-1:0] square;
assign square = candidate * candidate;

// Status predicates are generated by the datapath, never by the FSM.
assign status[0] = (square <= value);
assign status[1] = (bit_index == 0);

// Register-transfer operations. Later strobes retain nonblocking
// assignment priority when the same destination is written twice.

always @(posedge clk) if(!rst_n) begin
  result <= 0;
  value <= 0;
  root <= 0;
  bit_index <= 0;
end else begin
  if(control[0]) begin
    value <= x;
  end
  if(control[1]) begin
    root <= 0;
  end
  if(control[2]) begin
    bit_index <= (W - 1) / 2;
  end
  if(control[3]) begin
    root <= candidate;
  end
  if(control[4]) begin
    result <= (square <= value)? candidate : root;
  end
  if(control[5]) begin
    bit_index <= bit_index - 1;
  end
end

endmodule

// ---------------- TOP ----------------
module integer_sqrt #
(
  parameter W = 32
)
(
  input clk,
  input rst_n,
  input start,
  input [W-1:0] x,
  output [W-1:0] result,
  output busy,
  output done);
wire [5:0] control;
wire [1:0] status;
integer_sqrt_controller #(.W(W)) controller (
    .clk(clk),
    .rst_n(rst_n),
    .start(start),
    .status(status),
    .control(control),
    .busy(busy),
    .done(done)
);
integer_sqrt_datapath #(.W(W)) datapath (
    .clk(clk),
    .rst_n(rst_n),
    .x(x),
    .control(control),
    .status(status),
    .result(result)
);
endmodule
