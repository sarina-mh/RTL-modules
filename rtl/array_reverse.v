// Copy one element per cycle into the reversed position.

// =====================================================================
// array_reverse: complete controller + datapath + top in one Verilog file.
// Pulse start while busy=0. Inputs are latched on the accepting edge.
// Reset and port conventions are preserved from the original module.
// Packed array lane i occupies bits [i*W +: W], unless stated otherwise.
// =====================================================================
// control[0]: data <= data_in;
// control[1]: p <= 0;
// control[2]: data_out[((N - 1 - p) * W) +: W] <= data[(p * W) +: W];
// control[3]: p <= p + 1;

// ---------------- CONTROLLER ----------------
module array_reverse_controller #
(
  parameter W = 8,
  parameter N = 8
)
(
  input clk,
  input rst_n,
  input start,
  input [0:0] status,
  output reg [3:0] control,
  output reg busy,
  output reg done);


reg next_busy;
reg next_done;

// FSM state/handshake registers; all data writes are control strobes.

always @(posedge clk) if(!rst_n) begin
  busy <= 0;
  done <= 0;
end else begin
  busy <= next_busy;
  done <= next_done;
end


always @(*) begin
  next_busy = busy;
  next_done = done;
  control = 0;
  begin
    next_done = 0;
    if(start && !busy) begin
      control[0] = 1'b1;
      control[1] = 1'b1;
      next_busy = 1;
    end else if(busy) begin
      control[2] = 1'b1;
      if(status[0]) begin
        next_busy = 0;
        next_done = 1;
      end else control[3] = 1'b1;
    end
  end
end

endmodule

// ---------------- DATAPATH ----------------
module array_reverse_datapath #
(
  parameter W = 8,
  parameter N = 8
)
(
  input clk,
  input rst_n,
  input [N*W-1:0] data_in,
  input [3:0] control,
  output [0:0] status,
  output reg [N*W-1:0] data_out);
reg [N*W-1:0] data;
integer p;

// Status predicates are generated by the datapath, never by the FSM.
assign status[0] = (p == N - 1);

// Register-transfer operations. Later strobes retain nonblocking
// assignment priority when the same destination is written twice.

always @(posedge clk) if(!rst_n) begin
  data <= 0;
  data_out <= 0;
  p <= 0;
end else begin
  if(control[0]) begin
    data <= data_in;
  end
  if(control[1]) begin
    p <= 0;
  end
  if(control[2]) begin
    data_out[((N - 1 - p) * W) +: W] <= data[(p * W) +: W];
  end
  if(control[3]) begin
    p <= p + 1;
  end
end

endmodule

// ---------------- TOP ----------------
module array_reverse #
(
  parameter W = 8,
  parameter N = 8
)
(
  input clk,
  input rst_n,
  input start,
  input [N*W-1:0] data_in,
  output [N*W-1:0] data_out,
  output busy,
  output done);
wire [3:0] control;
wire [0:0] status;
array_reverse_controller #(.W(W), .N(N)) controller (
    .clk(clk),
    .rst_n(rst_n),
    .start(start),
    .status(status),
    .control(control),
    .busy(busy),
    .done(done)
);
array_reverse_datapath #(.W(W), .N(N)) datapath (
    .clk(clk),
    .rst_n(rst_n),
    .data_in(data_in),
    .control(control),
    .status(status),
    .data_out(data_out)
);
endmodule
