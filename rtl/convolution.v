// Full linear convolution y[t]=sum_k a[k]*b[t-k], length NA+NB-1.
// Unsigned or signed integer inputs, one valid MAC per cycle.

// =====================================================================
// convolution: complete controller + datapath + top in one Verilog file.
// Pulse start while busy=0. Inputs are latched on the accepting edge.
// Reset and port conventions are preserved from the original module.
// Packed array lane i occupies bits [i*W +: W], unless stated otherwise.
// =====================================================================
// control[0]: sa <= a;
// control[1]: sb <= b;
// control[2]: total <= 0;
// control[3]: t <= 0;
// control[4]: k <= 0;
// control[5]: result[(t * AW) +: AW] <= total + extended;
// control[6]: total <= 0;
// control[7]: k <= 0;
// control[8]: t <= t + 1;
// control[9]: total <= total + extended;
// control[10]: k <= k + 1;

// ---------------- CONTROLLER ----------------
module convolution_controller #
(
  parameter W = 8,
  parameter NA = 4,
  parameter NB = 3,
  parameter SIGNED = 0,
  parameter AW = 2 * W + $clog2(((NA < NB)? NA : NB))
)
(
  input clk,
  input rst_n,
  input start,
  input [1:0] status,
  output reg [10:0] control,
  output reg busy,
  output reg done);


reg next_busy;
reg next_done;

// FSM state/handshake registers; all data writes are control strobes.

always @(posedge clk) if(!rst_n) begin
  busy <= 0;
  done <= 0;
end else begin
  busy <= next_busy;
  done <= next_done;
end


always @(*) begin
  next_busy = busy;
  next_done = done;
  control = 0;
  begin
    next_done = 0;
    if(start && !busy) begin
      control[0] = 1'b1;
      control[1] = 1'b1;
      control[2] = 1'b1;
      control[3] = 1'b1;
      control[4] = 1'b1;
      next_busy = 1;
    end else if(busy) begin
      if(status[0]) begin
        control[5] = 1'b1;
        control[6] = 1'b1;
        control[7] = 1'b1;
        if(status[1]) begin
          next_busy = 0;
          next_done = 1;
        end else control[8] = 1'b1;
      end else begin
        control[9] = 1'b1;
        control[10] = 1'b1;
      end
    end
  end
end

endmodule

// ---------------- DATAPATH ----------------
module convolution_datapath #
(
  parameter W = 8,
  parameter NA = 4,
  parameter NB = 3,
  parameter SIGNED = 0,
  parameter AW = 2 * W + $clog2(((NA < NB)? NA : NB))
)
(
  input clk,
  input rst_n,
  input [NA*W-1:0] a,
  input [NB*W-1:0] b,
  input [10:0] control,
  output [1:0] status,
  output reg [(NA+NB-1)*AW-1:0] result);
reg [NA*W-1:0] sa;
reg [NB*W-1:0] sb;
reg [AW-1:0] total;
integer t;
integer k;
wire valid_pair;
assign valid_pair = (t >= k) && (t - k < NB);
wire [W-1:0] x;
assign x = sa[(k * W) +: W];
wire [W-1:0] y;
assign y = sb[(((valid_pair)? t - k : 0) * W) +: W];
wire [2*W-1:0] product;
wire [AW-1:0] extended;

generate if(SIGNED) begin : signed_math
  wire signed [AW-1:0] sign_extended;
  assign product = $signed(x) * $signed(y);
  assign sign_extended = $signed(product);
  assign extended = (valid_pair)? sign_extended : { AW{ 1'b0 } };
end else begin : unsigned_math
  assign product = x * y;
  assign extended = (valid_pair)? product : { AW{ 1'b0 } };
end
endgenerate


// Status predicates are generated by the datapath, never by the FSM.
assign status[0] = (k == NA - 1);
assign status[1] = (t == NA + NB - 2);

// Register-transfer operations. Later strobes retain nonblocking
// assignment priority when the same destination is written twice.

always @(posedge clk) if(!rst_n) begin
  sa <= 0;
  sb <= 0;
  result <= 0;
  total <= 0;
  t <= 0;
  k <= 0;
end else begin
  if(control[0]) begin
    sa <= a;
  end
  if(control[1]) begin
    sb <= b;
  end
  if(control[2]) begin
    total <= 0;
  end
  if(control[3]) begin
    t <= 0;
  end
  if(control[4]) begin
    k <= 0;
  end
  if(control[5]) begin
    result[(t * AW) +: AW] <= total + extended;
  end
  if(control[6]) begin
    total <= 0;
  end
  if(control[7]) begin
    k <= 0;
  end
  if(control[8]) begin
    t <= t + 1;
  end
  if(control[9]) begin
    total <= total + extended;
  end
  if(control[10]) begin
    k <= k + 1;
  end
end

endmodule

// ---------------- TOP ----------------
module convolution #
(
  parameter W = 8,
  parameter NA = 4,
  parameter NB = 3,
  parameter SIGNED = 0,
  parameter AW = 2 * W + $clog2(((NA < NB)? NA : NB))
)
(
  input clk,
  input rst_n,
  input start,
  input [NA*W-1:0] a,
  input [NB*W-1:0] b,
  output [(NA+NB-1)*AW-1:0] result,
  output busy,
  output done);
wire [10:0] control;
wire [1:0] status;
convolution_controller #(.W(W), .NA(NA), .NB(NB), .SIGNED(SIGNED), .AW(AW)) controller (
    .clk(clk),
    .rst_n(rst_n),
    .start(start),
    .status(status),
    .control(control),
    .busy(busy),
    .done(done)
);
convolution_datapath #(.W(W), .NA(NA), .NB(NB), .SIGNED(SIGNED), .AW(AW)) datapath (
    .clk(clk),
    .rst_n(rst_n),
    .a(a),
    .b(b),
    .control(control),
    .status(status),
    .result(result)
);
endmodule
