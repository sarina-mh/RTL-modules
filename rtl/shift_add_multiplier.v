// Module: shift_add_multiplier. Original group: algorithms.

// =====================================================================
// shift_add_multiplier: complete controller + datapath + top in one Verilog file.
// Pulse start while busy=0. Inputs are latched on the accepting edge.
// Reset and port conventions are preserved from the original module.
// Packed array lane i occupies bits [i*W +: W], unless stated otherwise.
// =====================================================================
// control[0]: acc <= 0;
// control[1]: multiplicand <= a;
// control[2]: multiplier <= b;
// control[3]: bits_left <= W;
// control[4]: acc <= acc + multiplicand;
// control[5]: multiplicand <= multiplicand << 1;
// control[6]: multiplier <= multiplier >> 1;
// control[7]: bits_left <= bits_left - 1;
// control[8]: product <= acc + ((multiplier[0])? multiplicand : { 2 * W{ 1'b0 } });

// ---------------- CONTROLLER ----------------
module shift_add_multiplier_controller #
(
  parameter W = 8
)
(
  input clk,
  input rst_n,
  input start,
  input [1:0] status,
  output reg [8:0] control,
  output reg busy,
  output reg done);


reg next_busy;
reg next_done;

// FSM state/handshake registers; all data writes are control strobes.

always @(posedge clk) if(!rst_n) begin
  busy <= 0;
  done <= 0;
end else begin
  busy <= next_busy;
  done <= next_done;
end


always @(*) begin
  next_busy = busy;
  next_done = done;
  control = 0;
  begin
    next_done = 0;
    if(start && !busy) begin
      control[0] = 1'b1;
      control[1] = 1'b1;
      control[2] = 1'b1;
      control[3] = 1'b1;
      next_busy = 1;
    end else if(busy) begin
      if(status[0]) control[4] = 1'b1;
      control[5] = 1'b1;
      control[6] = 1'b1;
      control[7] = 1'b1;
      if(status[1]) begin
        control[8] = 1'b1;
        next_busy = 0;
        next_done = 1;
      end
    end
  end
end

endmodule

// ---------------- DATAPATH ----------------
module shift_add_multiplier_datapath #
(
  parameter W = 8
)
(
  input clk,
  input rst_n,
  input [W-1:0] a,
  input [W-1:0] b,
  input [8:0] control,
  output [1:0] status,
  output reg [2*W-1:0] product);
reg [2*W-1:0] acc;
reg [2*W-1:0] multiplicand;
reg [W-1:0] multiplier;
integer bits_left;

// Status predicates are generated by the datapath, never by the FSM.
assign status[0] = multiplier[0];
assign status[1] = (bits_left == 1);

// Register-transfer operations. Later strobes retain nonblocking
// assignment priority when the same destination is written twice.

always @(posedge clk) if(!rst_n) begin
  acc <= 0;
  multiplicand <= 0;
  multiplier <= 0;
  product <= 0;
  bits_left <= 0;
end else begin
  if(control[0]) begin
    acc <= 0;
  end
  if(control[1]) begin
    multiplicand <= a;
  end
  if(control[2]) begin
    multiplier <= b;
  end
  if(control[3]) begin
    bits_left <= W;
  end
  if(control[4]) begin
    acc <= acc + multiplicand;
  end
  if(control[5]) begin
    multiplicand <= multiplicand << 1;
  end
  if(control[6]) begin
    multiplier <= multiplier >> 1;
  end
  if(control[7]) begin
    bits_left <= bits_left - 1;
  end
  if(control[8]) begin
    product <= acc + ((multiplier[0])? multiplicand : { 2 * W{ 1'b0 } });
  end
end

endmodule

// ---------------- TOP ----------------
module shift_add_multiplier #
(
  parameter W = 8
)
(
  input clk,
  input rst_n,
  input start,
  input [W-1:0] a,
  input [W-1:0] b,
  output [2*W-1:0] product,
  output busy,
  output done);
wire [8:0] control;
wire [1:0] status;
shift_add_multiplier_controller #(.W(W)) controller (
    .clk(clk),
    .rst_n(rst_n),
    .start(start),
    .status(status),
    .control(control),
    .busy(busy),
    .done(done)
);
shift_add_multiplier_datapath #(.W(W)) datapath (
    .clk(clk),
    .rst_n(rst_n),
    .a(a),
    .b(b),
    .control(control),
    .status(status),
    .product(product)
);
endmodule
