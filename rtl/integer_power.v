// Exponentiation by squaring, modulo 2**W. Defines a**0=1, including 0**0.

// =====================================================================
// integer_power: complete controller + datapath + top in one Verilog file.
// Pulse start while busy=0. Inputs are latched on the accepting edge.
// Reset and port conventions are preserved from the original module.
// Packed array lane i occupies bits [i*W +: W], unless stated otherwise.
// =====================================================================
// control[0]: base <= a;
// control[1]: total <= 1;
// control[2]: power_left <= exponent;
// control[3]: result <= total;
// control[4]: total <= total * base;
// control[5]: base <= base * base;
// control[6]: power_left <= power_left >> 1;

// ---------------- CONTROLLER ----------------
module integer_power_controller #
(
  parameter W = 16,
  parameter E = 8
)
(
  input clk,
  input rst_n,
  input start,
  input [1:0] status,
  output reg [6:0] control,
  output reg busy,
  output reg done);


reg next_busy;
reg next_done;

// FSM state/handshake registers; all data writes are control strobes.

always @(posedge clk) if(!rst_n) begin
  busy <= 0;
  done <= 0;
end else begin
  busy <= next_busy;
  done <= next_done;
end


always @(*) begin
  next_busy = busy;
  next_done = done;
  control = 0;
  begin
    next_done = 0;
    if(start && !busy) begin
      control[0] = 1'b1;
      control[1] = 1'b1;
      control[2] = 1'b1;
      next_busy = 1;
    end else if(busy) begin
      if(status[0]) begin
        control[3] = 1'b1;
        next_busy = 0;
        next_done = 1;
      end else begin
        if(status[1]) control[4] = 1'b1;
        control[5] = 1'b1;
        control[6] = 1'b1;
      end
    end
  end
end

endmodule

// ---------------- DATAPATH ----------------
module integer_power_datapath #
(
  parameter W = 16,
  parameter E = 8
)
(
  input clk,
  input rst_n,
  input [W-1:0] a,
  input [E-1:0] exponent,
  input [6:0] control,
  output [1:0] status,
  output reg [W-1:0] result);
reg [W-1:0] base;
reg [W-1:0] total;
reg [E-1:0] power_left;

// Status predicates are generated by the datapath, never by the FSM.
assign status[0] = (power_left == 0);
assign status[1] = power_left[0];

// Register-transfer operations. Later strobes retain nonblocking
// assignment priority when the same destination is written twice.

always @(posedge clk) if(!rst_n) begin
  result <= 0;
  base <= 0;
  total <= 0;
  power_left <= 0;
end else begin
  if(control[0]) begin
    base <= a;
  end
  if(control[1]) begin
    total <= 1;
  end
  if(control[2]) begin
    power_left <= exponent;
  end
  if(control[3]) begin
    result <= total;
  end
  if(control[4]) begin
    total <= total * base;
  end
  if(control[5]) begin
    base <= base * base;
  end
  if(control[6]) begin
    power_left <= power_left >> 1;
  end
end

endmodule

// ---------------- TOP ----------------
module integer_power #
(
  parameter W = 16,
  parameter E = 8
)
(
  input clk,
  input rst_n,
  input start,
  input [W-1:0] a,
  input [E-1:0] exponent,
  output [W-1:0] result,
  output busy,
  output done);
wire [6:0] control;
wire [1:0] status;
integer_power_controller #(.W(W), .E(E)) controller (
    .clk(clk),
    .rst_n(rst_n),
    .start(start),
    .status(status),
    .control(control),
    .busy(busy),
    .done(done)
);
integer_power_datapath #(.W(W), .E(E)) datapath (
    .clk(clk),
    .rst_n(rst_n),
    .a(a),
    .exponent(exponent),
    .control(control),
    .status(status),
    .result(result)
);
endmodule
