// Stable enumeration/rank sort: count smaller keys plus earlier equal keys.
// N comparisons per item, then place it at its unique rank.

// =====================================================================
// rank_sort: complete controller + datapath + top in one Verilog file.
// Pulse start while busy=0. Inputs are latched on the accepting edge.
// Reset and port conventions are preserved from the original module.
// Packed array lane i occupies bits [i*W +: W], unless stated otherwise.
// =====================================================================
// control[0]: data <= data_in;
// control[1]: i <= 0;
// control[2]: j <= 0;
// control[3]: rank_value <= 0;
// control[4]: data_out[(rank_value * W) +: W] <= b;
// control[5]: i <= i + 1;
// control[6]: j <= 0;
// control[7]: rank_value <= 0;
// control[8]: rank_value <= rank_value + 1;
// control[9]: j <= j + 1;

// ---------------- CONTROLLER ----------------
module rank_sort_controller #
(
  parameter W = 8,
  parameter N = 8,
  parameter SIGNED = 0
)
(
  input clk,
  input rst_n,
  input start,
  input [4:0] status,
  output reg [9:0] control,
  output reg busy,
  output reg done);

reg placing;
reg finish;
reg next_busy;
reg next_done;
reg next_finish;
reg next_placing;

// FSM state/handshake registers; all data writes are control strobes.

always @(posedge clk) if(!rst_n) begin
  busy <= 0;
  done <= 0;
  placing <= 0;
  finish <= 0;
end else begin
  busy <= next_busy;
  done <= next_done;
  finish <= next_finish;
  placing <= next_placing;
end


always @(*) begin
  next_busy = busy;
  next_done = done;
  next_finish = finish;
  next_placing = placing;
  control = 0;
  begin
    next_done = 0;
    if(start && !busy) begin
      control[0] = 1'b1;
      control[1] = 1'b1;
      control[2] = 1'b1;
      control[3] = 1'b1;
      next_placing = 0;
      next_finish = 0;
      next_busy = 1;
    end else if(busy) begin
      if(finish) begin
        next_busy = 0;
        next_done = 1;
      end else if(placing) begin
        control[4] = 1'b1;
        if(status[0]) next_finish = 1;
        else begin
          control[5] = 1'b1;
          control[6] = 1'b1;
          control[7] = 1'b1;
          next_placing = 0;
        end
      end else begin
        if(status[1] || status[2] && status[3]) control[8] = 1'b1;
        if(status[4]) next_placing = 1;
        else control[9] = 1'b1;
      end
    end
  end
end

endmodule

// ---------------- DATAPATH ----------------
module rank_sort_datapath #
(
  parameter W = 8,
  parameter N = 8,
  parameter SIGNED = 0
)
(
  input clk,
  input rst_n,
  input [N*W-1:0] data_in,
  input [9:0] control,
  output [4:0] status,
  output reg [N*W-1:0] data_out);
reg [N*W-1:0] data;
integer i;
integer j;
integer rank_value;
integer k;
wire [W-1:0] a;
assign a = data[(j * W) +: W];
wire [W-1:0] b;
assign b = data[(i * W) +: W];
wire smaller;
assign smaller = (SIGNED)? $signed(a) < $signed(b) : a < b;

// Status predicates are generated by the datapath, never by the FSM.
assign status[0] = (i == N - 1);
assign status[1] = smaller;
assign status[2] = (a == b);
assign status[3] = (j < i);
assign status[4] = (j == N - 1);

// Register-transfer operations. Later strobes retain nonblocking
// assignment priority when the same destination is written twice.

always @(posedge clk) if(!rst_n) begin
  data_out <= 0;
  data <= 0;
  i <= 0;
  j <= 0;
  rank_value <= 0;
end else begin
  if(control[0]) begin
    data <= data_in;
  end
  if(control[1]) begin
    i <= 0;
  end
  if(control[2]) begin
    j <= 0;
  end
  if(control[3]) begin
    rank_value <= 0;
  end
  if(control[4]) begin
    data_out[(rank_value * W) +: W] <= b;
  end
  if(control[5]) begin
    i <= i + 1;
  end
  if(control[6]) begin
    j <= 0;
  end
  if(control[7]) begin
    rank_value <= 0;
  end
  if(control[8]) begin
    rank_value <= rank_value + 1;
  end
  if(control[9]) begin
    j <= j + 1;
  end
end

endmodule

// ---------------- TOP ----------------
module rank_sort #
(
  parameter W = 8,
  parameter N = 8,
  parameter SIGNED = 0
)
(
  input clk,
  input rst_n,
  input start,
  input [N*W-1:0] data_in,
  output [N*W-1:0] data_out,
  output busy,
  output done);
wire [9:0] control;
wire [4:0] status;
rank_sort_controller #(.W(W), .N(N), .SIGNED(SIGNED)) controller (
    .clk(clk),
    .rst_n(rst_n),
    .start(start),
    .status(status),
    .control(control),
    .busy(busy),
    .done(done)
);
rank_sort_datapath #(.W(W), .N(N), .SIGNED(SIGNED)) datapath (
    .clk(clk),
    .rst_n(rst_n),
    .data_in(data_in),
    .control(control),
    .status(status),
    .data_out(data_out)
);
endmodule
