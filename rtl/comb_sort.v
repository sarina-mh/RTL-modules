// Comb sort with a 1.3 shrink factor. Final gap=1 repeats until no swaps.

// =====================================================================
// comb_sort: complete controller + datapath + top in one Verilog file.
// Pulse start while busy=0. Inputs are latched on the accepting edge.
// Reset and port conventions are preserved from the original module.
// Packed array lane i occupies bits [i*W +: W], unless stated otherwise.
// =====================================================================
// control[0]: for(k=0; k<N; k=k+1) mem[k] <= data_in[(k * W) +: W];
// control[1]: gap <= (N * 10 / 13 > 0)? N * 10 / 13 : 1;
// control[2]: p <= 0;
// control[3]: changed <= 0;
// control[4]: for(k=0; k<N; k=k+1) data_out[(k * W) +: W] <= mem[k];
// control[5]: mem[p] <= mem[p + gap];
// control[6]: mem[p + gap] <= mem[p];
// control[7]: changed <= 1;
// control[8]: gap <= new_gap;
// control[9]: p <= 0;
// control[10]: changed <= 0;
// control[11]: p <= p + 1;

// ---------------- CONTROLLER ----------------
module comb_sort_controller #
(
  parameter W = 8,
  parameter N = 8,
  parameter SIGNED = 0
)
(
  input clk,
  input rst_n,
  input start,
  input [4:0] status,
  output reg [11:0] control,
  output reg busy,
  output reg done);

reg finish;
reg next_busy;
reg next_done;
reg next_finish;

// FSM state/handshake registers; all data writes are control strobes.

always @(posedge clk) if(!rst_n) begin
  busy <= 0;
  done <= 0;
  finish <= 0;
end else begin
  busy <= next_busy;
  done <= next_done;
  finish <= next_finish;
end


always @(*) begin
  next_busy = busy;
  next_done = done;
  next_finish = finish;
  control = 0;
  begin
    next_done = 0;
    if(start && !busy) begin
      control[0] = 1'b1;
      control[1] = 1'b1;
      control[2] = 1'b1;
      control[3] = 1'b1;
      next_finish = N == 1;
      next_busy = 1;
    end else if(busy) begin
      if(finish) begin
        control[4] = 1'b1;
        next_busy = 0;
        next_done = 1;
      end else begin
        if(status[0]) begin
          control[5] = 1'b1;
          control[6] = 1'b1;
          control[7] = 1'b1;
        end
        if(status[1]) begin
          if(status[2] && status[3] && status[4]) next_finish = 1;
          else begin
            control[8] = 1'b1;
            control[9] = 1'b1;
            control[10] = 1'b1;
          end
        end else control[11] = 1'b1;
      end
    end
  end
end

endmodule

// ---------------- DATAPATH ----------------
module comb_sort_datapath #
(
  parameter W = 8,
  parameter N = 8,
  parameter SIGNED = 0
)
(
  input clk,
  input rst_n,
  input [N*W-1:0] data_in,
  input [11:0] control,
  output [4:0] status,
  output reg [N*W-1:0] data_out);
reg [W-1:0] mem [0:N-1];
integer gap;
integer p;
integer k;
integer new_gap;
reg changed;
wire greater;
assign greater = (SIGNED)? $signed(mem[p]) > $signed(mem[(p + gap < N)? p + gap : 0]) : mem[p] > mem[(p + gap < N)? p + gap : 0];

always @(*) begin
  new_gap = gap * 10 / 13;
  if(new_gap < 1) new_gap = 1;
end


// Status predicates are generated by the datapath, never by the FSM.
assign status[0] = greater;
assign status[1] = (p + gap == N - 1);
assign status[2] = (gap == 1);
assign status[3] = (!changed);
assign status[4] = (!greater);

// Register-transfer operations. Later strobes retain nonblocking
// assignment priority when the same destination is written twice.

always @(posedge clk) if(!rst_n) begin
  data_out <= 0;
  gap <= 1;
  p <= 0;
  changed <= 0;
  for(k=0; k<N; k=k+1) mem[k] <= 0;
end else begin
  if(control[0]) begin
    for(k=0; k<N; k=k+1) mem[k] <= data_in[(k * W) +: W];
  end
  if(control[1]) begin
    gap <= (N * 10 / 13 > 0)? N * 10 / 13 : 1;
  end
  if(control[2]) begin
    p <= 0;
  end
  if(control[3]) begin
    changed <= 0;
  end
  if(control[4]) begin
    for(k=0; k<N; k=k+1) data_out[(k * W) +: W] <= mem[k];
  end
  if(control[5]) begin
    mem[p] <= mem[p + gap];
  end
  if(control[6]) begin
    mem[p + gap] <= mem[p];
  end
  if(control[7]) begin
    changed <= 1;
  end
  if(control[8]) begin
    gap <= new_gap;
  end
  if(control[9]) begin
    p <= 0;
  end
  if(control[10]) begin
    changed <= 0;
  end
  if(control[11]) begin
    p <= p + 1;
  end
end

endmodule

// ---------------- TOP ----------------
module comb_sort #
(
  parameter W = 8,
  parameter N = 8,
  parameter SIGNED = 0
)
(
  input clk,
  input rst_n,
  input start,
  input [N*W-1:0] data_in,
  output [N*W-1:0] data_out,
  output busy,
  output done);
wire [11:0] control;
wire [4:0] status;
comb_sort_controller #(.W(W), .N(N), .SIGNED(SIGNED)) controller (
    .clk(clk),
    .rst_n(rst_n),
    .start(start),
    .status(status),
    .control(control),
    .busy(busy),
    .done(done)
);
comb_sort_datapath #(.W(W), .N(N), .SIGNED(SIGNED)) datapath (
    .clk(clk),
    .rst_n(rst_n),
    .data_in(data_in),
    .control(control),
    .status(status),
    .data_out(data_out)
);
endmodule
