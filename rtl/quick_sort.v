// Iterative Lomuto quicksort. Explicit N-entry stack replaces recursion.
// Ascending order; W,N >= 1. start is accepted only while !busy.

// =====================================================================
// quick_sort: complete controller + datapath + top in one Verilog file.
// Pulse start while busy=0. Inputs are latched on the accepting edge.
// Reset and port conventions are preserved from the original module.
// Packed array lane i occupies bits [i*W +: W], unless stated otherwise.
// =====================================================================
// control[0]: for(k=0; k<N; k=k+1) mem[k] <= data_in[(k * W) +: W];
// control[1]: stack_lo[0] <= 0;
// control[2]: stack_hi[0] <= N - 1;
// control[3]: sp <= 1;
// control[4]: lo <= stack_lo[sp - 1];
// control[5]: hi <= stack_hi[sp - 1];
// control[6]: sp <= sp - 1;
// control[7]: pivot <= mem[hi];
// control[8]: i <= lo;
// control[9]: j <= lo;
// control[10]: mem[i] <= mem[j];
// control[11]: mem[j] <= mem[i];
// control[12]: i <= i + 1;
// control[13]: j <= j + 1;
// control[14]: mem[i] <= mem[hi];
// control[15]: mem[hi] <= mem[i];
// control[16]: stack_lo[sp] <= lo;
// control[17]: stack_hi[sp] <= i - 1;
// control[18]: stack_lo[sp + 1] <= i + 1;
// control[19]: stack_hi[sp + 1] <= hi;
// control[20]: sp <= sp + 2;
// control[21]: stack_lo[sp] <= lo;
// control[22]: stack_hi[sp] <= i - 1;
// control[23]: sp <= sp + 1;
// control[24]: stack_lo[sp] <= i + 1;
// control[25]: stack_hi[sp] <= hi;
// control[26]: sp <= sp + 1;
// control[27]: for(k=0; k<N; k=k+1) data_out[(k * W) +: W] <= mem[k];

// ---------------- CONTROLLER ----------------
module quick_sort_controller #
(
  parameter W = 8,
  parameter N = 8,
  parameter SIGNED = 0
)
(
  input clk,
  input rst_n,
  input start,
  input [5:0] status,
  output reg [27:0] control,
  output reg busy,
  output reg done);

reg [2:0] state;
reg next_busy;
reg next_done;
reg [2:0] next_state;

// FSM state/handshake registers; all data writes are control strobes.

always @(posedge clk) if(!rst_n) begin
  busy <= 0;
  done <= 0;
  state <= 0;
end else begin
  busy <= next_busy;
  done <= next_done;
  state <= next_state;
end


always @(*) begin
  next_busy = busy;
  next_done = done;
  next_state = state;
  control = 0;
  begin
    next_done = 0;
    if(start && !busy) begin
      control[0] = 1'b1;
      control[1] = 1'b1;
      control[2] = 1'b1;
      control[3] = 1'b1;
      next_busy = 1;
      next_state = 0;
    end else if(busy) case(state)
      0: if(status[0]) next_state = 4;
      else begin
        control[4] = 1'b1;
        control[5] = 1'b1;
        control[6] = 1'b1;
        next_state = 1;
      end
      1: if(status[1]) next_state = 0;
      else begin
        control[7] = 1'b1;
        control[8] = 1'b1;
        control[9] = 1'b1;
        next_state = 2;
      end
      2: if(status[2]) next_state = 3;
      else begin
        if(status[3]) begin
          control[10] = 1'b1;
          control[11] = 1'b1;
          control[12] = 1'b1;
        end
        control[13] = 1'b1;
      end
      3: begin
        control[14] = 1'b1;
        control[15] = 1'b1;
        if(status[4] && status[5]) begin
          control[16] = 1'b1;
          control[17] = 1'b1;
          control[18] = 1'b1;
          control[19] = 1'b1;
          control[20] = 1'b1;
        end else if(status[4]) begin
          control[21] = 1'b1;
          control[22] = 1'b1;
          control[23] = 1'b1;
        end else if(status[5]) begin
          control[24] = 1'b1;
          control[25] = 1'b1;
          control[26] = 1'b1;
        end
        next_state = 0;
      end
      4: begin
        control[27] = 1'b1;
        next_busy = 0;
        next_done = 1;
      end
      default: next_state = 0;
    endcase
  end
end

endmodule

// ---------------- DATAPATH ----------------
module quick_sort_datapath #
(
  parameter W = 8,
  parameter N = 8,
  parameter SIGNED = 0
)
(
  input clk,
  input rst_n,
  input [N*W-1:0] data_in,
  input [27:0] control,
  output [5:0] status,
  output reg [N*W-1:0] data_out);
reg [W-1:0] mem [0:N-1];
reg [W-1:0] pivot;
reg signed [31:0] stack_lo [0:N-1];
reg signed [31:0] stack_hi [0:N-1];
integer sp;
integer lo;
integer hi;
integer i;
integer j;
integer k;
wire le;
assign le = (SIGNED)? $signed(mem[j]) <= $signed(pivot) : mem[j] <= pivot;

// Status predicates are generated by the datapath, never by the FSM.
assign status[0] = (sp == 0);
assign status[1] = (lo >= hi);
assign status[2] = (j == hi);
assign status[3] = le;
assign status[4] = (lo < i - 1);
assign status[5] = (i + 1 < hi);

// Register-transfer operations. Later strobes retain nonblocking
// assignment priority when the same destination is written twice.

always @(posedge clk) if(!rst_n) begin
  data_out <= 0;
  sp <= 0;
  lo <= 0;
  hi <= 0;
  i <= 0;
  j <= 0;
  pivot <= 0;
  for(k=0; k<N; k=k+1) begin
    mem[k] <= 0;
    stack_lo[k] <= 0;
    stack_hi[k] <= 0;
  end
end else begin
  if(control[0]) begin
    for(k=0; k<N; k=k+1) mem[k] <= data_in[(k * W) +: W];
  end
  if(control[1]) begin
    stack_lo[0] <= 0;
  end
  if(control[2]) begin
    stack_hi[0] <= N - 1;
  end
  if(control[3]) begin
    sp <= 1;
  end
  if(control[4]) begin
    lo <= stack_lo[sp - 1];
  end
  if(control[5]) begin
    hi <= stack_hi[sp - 1];
  end
  if(control[6]) begin
    sp <= sp - 1;
  end
  if(control[7]) begin
    pivot <= mem[hi];
  end
  if(control[8]) begin
    i <= lo;
  end
  if(control[9]) begin
    j <= lo;
  end
  if(control[10]) begin
    mem[i] <= mem[j];
  end
  if(control[11]) begin
    mem[j] <= mem[i];
  end
  if(control[12]) begin
    i <= i + 1;
  end
  if(control[13]) begin
    j <= j + 1;
  end
  if(control[14]) begin
    mem[i] <= mem[hi];
  end
  if(control[15]) begin
    mem[hi] <= mem[i];
  end
  if(control[16]) begin
    stack_lo[sp] <= lo;
  end
  if(control[17]) begin
    stack_hi[sp] <= i - 1;
  end
  if(control[18]) begin
    stack_lo[sp + 1] <= i + 1;
  end
  if(control[19]) begin
    stack_hi[sp + 1] <= hi;
  end
  if(control[20]) begin
    sp <= sp + 2;
  end
  if(control[21]) begin
    stack_lo[sp] <= lo;
  end
  if(control[22]) begin
    stack_hi[sp] <= i - 1;
  end
  if(control[23]) begin
    sp <= sp + 1;
  end
  if(control[24]) begin
    stack_lo[sp] <= i + 1;
  end
  if(control[25]) begin
    stack_hi[sp] <= hi;
  end
  if(control[26]) begin
    sp <= sp + 1;
  end
  if(control[27]) begin
    for(k=0; k<N; k=k+1) data_out[(k * W) +: W] <= mem[k];
  end
end

endmodule

// ---------------- TOP ----------------
module quick_sort #
(
  parameter W = 8,
  parameter N = 8,
  parameter SIGNED = 0
)
(
  input clk,
  input rst_n,
  input start,
  input [N*W-1:0] data_in,
  output [N*W-1:0] data_out,
  output busy,
  output done);
wire [27:0] control;
wire [5:0] status;
quick_sort_controller #(.W(W), .N(N), .SIGNED(SIGNED)) controller (
    .clk(clk),
    .rst_n(rst_n),
    .start(start),
    .status(status),
    .control(control),
    .busy(busy),
    .done(done)
);
quick_sort_datapath #(.W(W), .N(N), .SIGNED(SIGNED)) datapath (
    .clk(clk),
    .rst_n(rst_n),
    .data_in(data_in),
    .control(control),
    .status(status),
    .data_out(data_out)
);
endmodule
