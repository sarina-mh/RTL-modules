// Bidirectional bubble (cocktail shaker) sort, one adjacent pair per cycle.

// =====================================================================
// cocktail_sort: complete controller + datapath + top in one Verilog file.
// Pulse start while busy=0. Inputs are latched on the accepting edge.
// Reset and port conventions are preserved from the original module.
// Packed array lane i occupies bits [i*W +: W], unless stated otherwise.
// =====================================================================
// control[0]: for(k=0; k<N; k=k+1) mem[k] <= data_in[(k * W) +: W];
// control[1]: low <= 0;
// control[2]: high <= N - 1;
// control[3]: p <= 0;
// control[4]: for(k=0; k<N; k=k+1) data_out[(k * W) +: W] <= mem[k];
// control[5]: mem[p] <= mem[p + 1];
// control[6]: mem[p + 1] <= mem[p];
// control[7]: high <= high - 1;
// control[8]: p <= high - 2;
// control[9]: p <= p + 1;
// control[10]: low <= low + 1;
// control[11]: p <= low + 1;
// control[12]: p <= p - 1;

// ---------------- CONTROLLER ----------------
module cocktail_sort_controller #
(
  parameter W = 8,
  parameter N = 8,
  parameter SIGNED = 0
)
(
  input clk,
  input rst_n,
  input start,
  input [4:0] status,
  output reg [12:0] control,
  output reg busy,
  output reg done);

reg reverse;
reg finish;
reg next_busy;
reg next_done;
reg next_finish;
reg next_reverse;

// FSM state/handshake registers; all data writes are control strobes.

always @(posedge clk) if(!rst_n) begin
  busy <= 0;
  done <= 0;
  reverse <= 0;
  finish <= 0;
end else begin
  busy <= next_busy;
  done <= next_done;
  finish <= next_finish;
  reverse <= next_reverse;
end


always @(*) begin
  next_busy = busy;
  next_done = done;
  next_finish = finish;
  next_reverse = reverse;
  control = 0;
  begin
    next_done = 0;
    if(start && !busy) begin
      control[0] = 1'b1;
      control[1] = 1'b1;
      control[2] = 1'b1;
      control[3] = 1'b1;
      next_reverse = 0;
      next_finish = N == 1;
      next_busy = 1;
    end else if(busy) begin
      if(finish) begin
        control[4] = 1'b1;
        next_busy = 0;
        next_done = 1;
      end else begin
        if(status[0]) begin
          control[5] = 1'b1;
          control[6] = 1'b1;
        end
        if(!reverse) begin
          if(status[1]) begin
            control[7] = 1'b1;
            next_reverse = 1;
            control[8] = 1'b1;
            if(status[2]) next_finish = 1;
          end else control[9] = 1'b1;
        end else if(status[3]) begin
          control[10] = 1'b1;
          next_reverse = 0;
          control[11] = 1'b1;
          if(status[4]) next_finish = 1;
        end else control[12] = 1'b1;
      end
    end
  end
end

endmodule

// ---------------- DATAPATH ----------------
module cocktail_sort_datapath #
(
  parameter W = 8,
  parameter N = 8,
  parameter SIGNED = 0
)
(
  input clk,
  input rst_n,
  input [N*W-1:0] data_in,
  input [12:0] control,
  output [4:0] status,
  output reg [N*W-1:0] data_out);
reg [W-1:0] mem [0:N-1];
integer low;
integer high;
integer p;
integer k;
wire greater;
assign greater = (SIGNED)? $signed(mem[p]) > $signed(mem[(p + 1 < N)? p + 1 : 0]) : mem[p] > mem[(p + 1 < N)? p + 1 : 0];

// Status predicates are generated by the datapath, never by the FSM.
assign status[0] = greater;
assign status[1] = (p == high - 1);
assign status[2] = (high - 1 <= low);
assign status[3] = (p == low);
assign status[4] = (low + 1 >= high);

// Register-transfer operations. Later strobes retain nonblocking
// assignment priority when the same destination is written twice.

always @(posedge clk) if(!rst_n) begin
  data_out <= 0;
  low <= 0;
  high <= 0;
  p <= 0;
  for(k=0; k<N; k=k+1) mem[k] <= 0;
end else begin
  if(control[0]) begin
    for(k=0; k<N; k=k+1) mem[k] <= data_in[(k * W) +: W];
  end
  if(control[1]) begin
    low <= 0;
  end
  if(control[2]) begin
    high <= N - 1;
  end
  if(control[3]) begin
    p <= 0;
  end
  if(control[4]) begin
    for(k=0; k<N; k=k+1) data_out[(k * W) +: W] <= mem[k];
  end
  if(control[5]) begin
    mem[p] <= mem[p + 1];
  end
  if(control[6]) begin
    mem[p + 1] <= mem[p];
  end
  if(control[7]) begin
    high <= high - 1;
  end
  if(control[8]) begin
    p <= high - 2;
  end
  if(control[9]) begin
    p <= p + 1;
  end
  if(control[10]) begin
    low <= low + 1;
  end
  if(control[11]) begin
    p <= low + 1;
  end
  if(control[12]) begin
    p <= p - 1;
  end
end

endmodule

// ---------------- TOP ----------------
module cocktail_sort #
(
  parameter W = 8,
  parameter N = 8,
  parameter SIGNED = 0
)
(
  input clk,
  input rst_n,
  input start,
  input [N*W-1:0] data_in,
  output [N*W-1:0] data_out,
  output busy,
  output done);
wire [12:0] control;
wire [4:0] status;
cocktail_sort_controller #(.W(W), .N(N), .SIGNED(SIGNED)) controller (
    .clk(clk),
    .rst_n(rst_n),
    .start(start),
    .status(status),
    .control(control),
    .busy(busy),
    .done(done)
);
cocktail_sort_datapath #(.W(W), .N(N), .SIGNED(SIGNED)) datapath (
    .clk(clk),
    .rst_n(rst_n),
    .data_in(data_in),
    .control(control),
    .status(status),
    .data_out(data_out)
);
endmodule
