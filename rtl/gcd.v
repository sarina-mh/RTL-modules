// Module: gcd. Original group: algorithms.
// Euclidean subtraction GCD: one subtraction per cycle, no divider inferred.

// =====================================================================
// gcd: complete controller + datapath + top in one Verilog file.
// Pulse start while busy=0. Inputs are latched on the accepting edge.
// Reset and port conventions are preserved from the original module.
// Packed array lane i occupies bits [i*W +: W], unless stated otherwise.
// =====================================================================
// control[0]: x <= a;
// control[1]: y <= b;
// control[2]: result <= (x == 0)? y : x;
// control[3]: x <= x - y;
// control[4]: y <= y - x;

// ---------------- CONTROLLER ----------------
module gcd_controller #
(
  parameter W = 16
)
(
  input clk,
  input rst_n,
  input start,
  input [3:0] status,
  output reg [4:0] control,
  output reg busy,
  output reg done);


reg next_busy;
reg next_done;

// FSM state/handshake registers; all data writes are control strobes.

always @(posedge clk) if(!rst_n) begin
  busy <= 0;
  done <= 0;
end else begin
  busy <= next_busy;
  done <= next_done;
end


always @(*) begin
  next_busy = busy;
  next_done = done;
  control = 0;
  begin
    next_done = 0;
    if(start && !busy) begin
      control[0] = 1'b1;
      control[1] = 1'b1;
      next_busy = 1;
    end else if(busy) begin
      if(status[0] || status[1] || status[2]) begin
        control[2] = 1'b1;
        next_busy = 0;
        next_done = 1;
      end else if(status[3]) control[3] = 1'b1;
      else control[4] = 1'b1;
    end
  end
end

endmodule

// ---------------- DATAPATH ----------------
module gcd_datapath #
(
  parameter W = 16
)
(
  input clk,
  input rst_n,
  input [W-1:0] a,
  input [W-1:0] b,
  input [4:0] control,
  output [3:0] status,
  output reg [W-1:0] result);
reg [W-1:0] x;
reg [W-1:0] y;

// Status predicates are generated by the datapath, never by the FSM.
assign status[0] = (x == 0);
assign status[1] = (y == 0);
assign status[2] = (x == y);
assign status[3] = (x > y);

// Register-transfer operations. Later strobes retain nonblocking
// assignment priority when the same destination is written twice.

always @(posedge clk) if(!rst_n) begin
  x <= 0;
  y <= 0;
  result <= 0;
end else begin
  if(control[0]) begin
    x <= a;
  end
  if(control[1]) begin
    y <= b;
  end
  if(control[2]) begin
    result <= (x == 0)? y : x;
  end
  if(control[3]) begin
    x <= x - y;
  end
  if(control[4]) begin
    y <= y - x;
  end
end

endmodule

// ---------------- TOP ----------------
module gcd #
(
  parameter W = 16
)
(
  input clk,
  input rst_n,
  input start,
  input [W-1:0] a,
  input [W-1:0] b,
  output [W-1:0] result,
  output busy,
  output done);
wire [4:0] control;
wire [3:0] status;
gcd_controller #(.W(W)) controller (
    .clk(clk),
    .rst_n(rst_n),
    .start(start),
    .status(status),
    .control(control),
    .busy(busy),
    .done(done)
);
gcd_datapath #(.W(W)) datapath (
    .clk(clk),
    .rst_n(rst_n),
    .a(a),
    .b(b),
    .control(control),
    .status(status),
    .result(result)
);
endmodule
