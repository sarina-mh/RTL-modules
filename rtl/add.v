// ============================================================================
// ماژول: add  (جمع‌کننده)
// ----------------------------------------------------------------------------
// کار کلی:
//   یک جمع‌کننده‌ی ترکیبی (بدون کلاک) با عرض قابل تنظیم است.
//   sum = a + b + cin  را حساب می‌کند و علاوه بر حاصل جمع، رقم نقلی خروجی
//   (cout) و سرریز علامت‌دار (overflow) را هم تولید می‌کند.
//
// پارامترها:
//   WIDTH : عرض بیت ورودی‌ها و خروجی (پیش‌فرض 8)
//
// ورودی‌ها:
//   a   : عملوند اول  (عرض WIDTH)
//   b   : عملوند دوم  (عرض WIDTH)
//   cin : رقم نقلی ورودی (Carry-In)
//
// خروجی‌ها:
//   sum      : حاصل جمع (عرض WIDTH)
//   cout     : رقم نقلی خروجی (Carry-Out)
//   overflow : سرریز علامت‌دار؛ اگر دو ورودی هم‌علامت باشند و نتیجه علامتش
//              با آن‌ها فرق کند یک می‌شود.
// ============================================================================
module add #(
    parameter WIDTH = 8
)(
    input  wire [WIDTH-1:0] a,
    input  wire [WIDTH-1:0] b,
    input  wire             cin,
    output wire [WIDTH-1:0] sum,
    output wire             cout,
    output wire             overflow
);

    // یک بیت بیشتر در نظر می‌گیریم تا رقم نقلی از دست نرود.
    wire [WIDTH:0] result;

    assign result = {1'b0, a} + {1'b0, b} + cin;

    assign sum  = result[WIDTH-1:0];
    assign cout = result[WIDTH];

    // سرریز علامت‌دار: دو عملوند هم‌علامت‌اند ولی نتیجه علامت دیگری دارد.
    assign overflow = (a[WIDTH-1] == b[WIDTH-1]) &&
                      (sum[WIDTH-1] != a[WIDTH-1]);

endmodule
