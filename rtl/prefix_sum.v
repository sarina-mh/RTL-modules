// Inclusive unsigned prefix sum. AW defaults to sufficient full precision.

// =====================================================================
// prefix_sum: complete controller + datapath + top in one Verilog file.
// Pulse start while busy=0. Inputs are latched on the accepting edge.
// Reset and port conventions are preserved from the original module.
// Packed array lane i occupies bits [i*W +: W], unless stated otherwise.
// =====================================================================
// control[0]: data <= data_in;
// control[1]: total <= 0;
// control[2]: p <= 0;
// control[3]: total <= next_total;
// control[4]: data_out[(p * AW) +: AW] <= next_total;
// control[5]: p <= p + 1;

// ---------------- CONTROLLER ----------------
module prefix_sum_controller #
(
  parameter W = 8,
  parameter N = 8,
  parameter AW = W + $clog2(N)
)
(
  input clk,
  input rst_n,
  input start,
  input [0:0] status,
  output reg [5:0] control,
  output reg busy,
  output reg done);


reg next_busy;
reg next_done;

// FSM state/handshake registers; all data writes are control strobes.

always @(posedge clk) if(!rst_n) begin
  busy <= 0;
  done <= 0;
end else begin
  busy <= next_busy;
  done <= next_done;
end


always @(*) begin
  next_busy = busy;
  next_done = done;
  control = 0;
  begin
    next_done = 0;
    if(start && !busy) begin
      control[0] = 1'b1;
      control[1] = 1'b1;
      control[2] = 1'b1;
      next_busy = 1;
    end else if(busy) begin
      control[3] = 1'b1;
      control[4] = 1'b1;
      if(status[0]) begin
        next_busy = 0;
        next_done = 1;
      end else control[5] = 1'b1;
    end
  end
end

endmodule

// ---------------- DATAPATH ----------------
module prefix_sum_datapath #
(
  parameter W = 8,
  parameter N = 8,
  parameter AW = W + $clog2(N)
)
(
  input clk,
  input rst_n,
  input [N*W-1:0] data_in,
  input [5:0] control,
  output [0:0] status,
  output reg [N*AW-1:0] data_out);
reg [N*W-1:0] data;
reg [AW-1:0] total;
integer p;
wire [AW-1:0] next_total;
assign next_total = total + data[(p * W) +: W];

// Status predicates are generated by the datapath, never by the FSM.
assign status[0] = (p == N - 1);

// Register-transfer operations. Later strobes retain nonblocking
// assignment priority when the same destination is written twice.

always @(posedge clk) if(!rst_n) begin
  data <= 0;
  data_out <= 0;
  total <= 0;
  p <= 0;
end else begin
  if(control[0]) begin
    data <= data_in;
  end
  if(control[1]) begin
    total <= 0;
  end
  if(control[2]) begin
    p <= 0;
  end
  if(control[3]) begin
    total <= next_total;
  end
  if(control[4]) begin
    data_out[(p * AW) +: AW] <= next_total;
  end
  if(control[5]) begin
    p <= p + 1;
  end
end

endmodule

// ---------------- TOP ----------------
module prefix_sum #
(
  parameter W = 8,
  parameter N = 8,
  parameter AW = W + $clog2(N)
)
(
  input clk,
  input rst_n,
  input start,
  input [N*W-1:0] data_in,
  output [N*AW-1:0] data_out,
  output busy,
  output done);
wire [5:0] control;
wire [0:0] status;
prefix_sum_controller #(.W(W), .N(N), .AW(AW)) controller (
    .clk(clk),
    .rst_n(rst_n),
    .start(start),
    .status(status),
    .control(control),
    .busy(busy),
    .done(done)
);
prefix_sum_datapath #(.W(W), .N(N), .AW(AW)) datapath (
    .clk(clk),
    .rst_n(rst_n),
    .data_in(data_in),
    .control(control),
    .status(status),
    .data_out(data_out)
);
endmodule
