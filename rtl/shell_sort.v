// Shell sort using halving gaps and gapped insertion, one shift per cycle.

// =====================================================================
// shell_sort: complete controller + datapath + top in one Verilog file.
// Pulse start while busy=0. Inputs are latched on the accepting edge.
// Reset and port conventions are preserved from the original module.
// Packed array lane i occupies bits [i*W +: W], unless stated otherwise.
// =====================================================================
// control[0]: for(k=0; k<N; k=k+1) mem[k] <= data_in[(k * W) +: W];
// control[1]: gap <= N / 2;
// control[2]: i <= N / 2;
// control[3]: key <= mem[i];
// control[4]: j <= i;
// control[5]: mem[j] <= mem[j - gap];
// control[6]: j <= j - gap;
// control[7]: mem[j] <= key;
// control[8]: i <= i + 1;
// control[9]: gap <= gap / 2;
// control[10]: i <= gap / 2;
// control[11]: for(k=0; k<N; k=k+1) data_out[(k * W) +: W] <= mem[k];

// ---------------- CONTROLLER ----------------
module shell_sort_controller #
(
  parameter W = 8,
  parameter N = 8,
  parameter SIGNED = 0
)
(
  input clk,
  input rst_n,
  input start,
  input [3:0] status,
  output reg [11:0] control,
  output reg busy,
  output reg done);

reg [1:0] state;
reg next_busy;
reg next_done;
reg [1:0] next_state;

// FSM state/handshake registers; all data writes are control strobes.

always @(posedge clk) if(!rst_n) begin
  busy <= 0;
  done <= 0;
  state <= 0;
end else begin
  busy <= next_busy;
  done <= next_done;
  state <= next_state;
end


always @(*) begin
  next_busy = busy;
  next_done = done;
  next_state = state;
  control = 0;
  begin
    next_done = 0;
    if(start && !busy) begin
      control[0] = 1'b1;
      control[1] = 1'b1;
      control[2] = 1'b1;
      next_state = (N == 1)? 3 : 0;
      next_busy = 1;
    end else if(busy) case(state)
      0: begin
        control[3] = 1'b1;
        control[4] = 1'b1;
        next_state = 1;
      end
      1: if(status[0] && status[1]) begin
        control[5] = 1'b1;
        control[6] = 1'b1;
      end else begin
        control[7] = 1'b1;
        next_state = 2;
      end
      2: if(status[2]) begin
        control[8] = 1'b1;
        next_state = 0;
      end else if(status[3]) begin
        control[9] = 1'b1;
        control[10] = 1'b1;
        next_state = 0;
      end else next_state = 3;
      3: begin
        control[11] = 1'b1;
        next_busy = 0;
        next_done = 1;
      end
      default: next_state = 0;
    endcase
  end
end

endmodule

// ---------------- DATAPATH ----------------
module shell_sort_datapath #
(
  parameter W = 8,
  parameter N = 8,
  parameter SIGNED = 0
)
(
  input clk,
  input rst_n,
  input [N*W-1:0] data_in,
  input [11:0] control,
  output [3:0] status,
  output reg [N*W-1:0] data_out);
reg [W-1:0] mem [0:N-1];
reg [W-1:0] key;
integer gap;
integer i;
integer j;
integer k;
wire greater;
assign greater = (SIGNED)? $signed(mem[(j >= gap)? j - gap : 0]) > $signed(key) : mem[(j >= gap)? j - gap : 0] > key;

// Status predicates are generated by the datapath, never by the FSM.
assign status[0] = (j >= gap);
assign status[1] = greater;
assign status[2] = (i + 1 < N);
assign status[3] = (gap > 1);

// Register-transfer operations. Later strobes retain nonblocking
// assignment priority when the same destination is written twice.

always @(posedge clk) if(!rst_n) begin
  data_out <= 0;
  gap <= 0;
  i <= 0;
  j <= 0;
  key <= 0;
  for(k=0; k<N; k=k+1) mem[k] <= 0;
end else begin
  if(control[0]) begin
    for(k=0; k<N; k=k+1) mem[k] <= data_in[(k * W) +: W];
  end
  if(control[1]) begin
    gap <= N / 2;
  end
  if(control[2]) begin
    i <= N / 2;
  end
  if(control[3]) begin
    key <= mem[i];
  end
  if(control[4]) begin
    j <= i;
  end
  if(control[5]) begin
    mem[j] <= mem[j - gap];
  end
  if(control[6]) begin
    j <= j - gap;
  end
  if(control[7]) begin
    mem[j] <= key;
  end
  if(control[8]) begin
    i <= i + 1;
  end
  if(control[9]) begin
    gap <= gap / 2;
  end
  if(control[10]) begin
    i <= gap / 2;
  end
  if(control[11]) begin
    for(k=0; k<N; k=k+1) data_out[(k * W) +: W] <= mem[k];
  end
end

endmodule

// ---------------- TOP ----------------
module shell_sort #
(
  parameter W = 8,
  parameter N = 8,
  parameter SIGNED = 0
)
(
  input clk,
  input rst_n,
  input start,
  input [N*W-1:0] data_in,
  output [N*W-1:0] data_out,
  output busy,
  output done);
wire [11:0] control;
wire [3:0] status;
shell_sort_controller #(.W(W), .N(N), .SIGNED(SIGNED)) controller (
    .clk(clk),
    .rst_n(rst_n),
    .start(start),
    .status(status),
    .control(control),
    .busy(busy),
    .done(done)
);
shell_sort_datapath #(.W(W), .N(N), .SIGNED(SIGNED)) datapath (
    .clk(clk),
    .rst_n(rst_n),
    .data_in(data_in),
    .control(control),
    .status(status),
    .data_out(data_out)
);
endmodule
