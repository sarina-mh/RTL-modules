// Odd-even transposition sort; N alternating even/odd adjacent passes.

// =====================================================================
// odd_even_sort: complete controller + datapath + top in one Verilog file.
// Pulse start while busy=0. Inputs are latched on the accepting edge.
// Reset and port conventions are preserved from the original module.
// Packed array lane i occupies bits [i*W +: W], unless stated otherwise.
// =====================================================================
// control[0]: for(k=0; k<N; k=k+1) mem[k] <= data_in[(k * W) +: W];
// control[1]: pass <= 0;
// control[2]: p <= 0;
// control[3]: for(k=0; k<N; k=k+1) data_out[(k * W) +: W] <= mem[k];
// control[4]: pass <= pass + 1;
// control[5]: p <= 1 - pass % 2;
// control[6]: mem[p] <= mem[p + 1];
// control[7]: mem[p + 1] <= mem[p];
// control[8]: p <= p + 2;

// ---------------- CONTROLLER ----------------
module odd_even_sort_controller #
(
  parameter W = 8,
  parameter N = 8,
  parameter SIGNED = 0
)
(
  input clk,
  input rst_n,
  input start,
  input [2:0] status,
  output reg [8:0] control,
  output reg busy,
  output reg done);

reg finish;
reg next_busy;
reg next_done;
reg next_finish;

// FSM state/handshake registers; all data writes are control strobes.

always @(posedge clk) if(!rst_n) begin
  busy <= 0;
  done <= 0;
  finish <= 0;
end else begin
  busy <= next_busy;
  done <= next_done;
  finish <= next_finish;
end


always @(*) begin
  next_busy = busy;
  next_done = done;
  next_finish = finish;
  control = 0;
  begin
    next_done = 0;
    if(start && !busy) begin
      control[0] = 1'b1;
      control[1] = 1'b1;
      control[2] = 1'b1;
      next_finish = N == 1;
      next_busy = 1;
    end else if(busy) begin
      if(finish) begin
        control[3] = 1'b1;
        next_busy = 0;
        next_done = 1;
      end else if(status[0]) begin
        if(status[1]) next_finish = 1;
        else begin
          control[4] = 1'b1;
          control[5] = 1'b1;
        end
      end else begin
        if(status[2]) begin
          control[6] = 1'b1;
          control[7] = 1'b1;
        end
        control[8] = 1'b1;
      end
    end
  end
end

endmodule

// ---------------- DATAPATH ----------------
module odd_even_sort_datapath #
(
  parameter W = 8,
  parameter N = 8,
  parameter SIGNED = 0
)
(
  input clk,
  input rst_n,
  input [N*W-1:0] data_in,
  input [8:0] control,
  output [2:0] status,
  output reg [N*W-1:0] data_out);
reg [W-1:0] mem [0:N-1];
integer pass;
integer p;
integer k;
wire greater;
assign greater = (SIGNED)? $signed(mem[(p < N)? p : 0]) > $signed(mem[(p + 1 < N)? p + 1 : 0]) : mem[(p < N)? p : 0] > mem[(p + 1 < N)? p + 1 : 0];

// Status predicates are generated by the datapath, never by the FSM.
assign status[0] = (p + 1 >= N);
assign status[1] = (pass == N - 1);
assign status[2] = greater;

// Register-transfer operations. Later strobes retain nonblocking
// assignment priority when the same destination is written twice.

always @(posedge clk) if(!rst_n) begin
  data_out <= 0;
  pass <= 0;
  p <= 0;
  for(k=0; k<N; k=k+1) mem[k] <= 0;
end else begin
  if(control[0]) begin
    for(k=0; k<N; k=k+1) mem[k] <= data_in[(k * W) +: W];
  end
  if(control[1]) begin
    pass <= 0;
  end
  if(control[2]) begin
    p <= 0;
  end
  if(control[3]) begin
    for(k=0; k<N; k=k+1) data_out[(k * W) +: W] <= mem[k];
  end
  if(control[4]) begin
    pass <= pass + 1;
  end
  if(control[5]) begin
    p <= 1 - pass % 2;
  end
  if(control[6]) begin
    mem[p] <= mem[p + 1];
  end
  if(control[7]) begin
    mem[p + 1] <= mem[p];
  end
  if(control[8]) begin
    p <= p + 2;
  end
end

endmodule

// ---------------- TOP ----------------
module odd_even_sort #
(
  parameter W = 8,
  parameter N = 8,
  parameter SIGNED = 0
)
(
  input clk,
  input rst_n,
  input start,
  input [N*W-1:0] data_in,
  output [N*W-1:0] data_out,
  output busy,
  output done);
wire [8:0] control;
wire [2:0] status;
odd_even_sort_controller #(.W(W), .N(N), .SIGNED(SIGNED)) controller (
    .clk(clk),
    .rst_n(rst_n),
    .start(start),
    .status(status),
    .control(control),
    .busy(busy),
    .done(done)
);
odd_even_sort_datapath #(.W(W), .N(N), .SIGNED(SIGNED)) datapath (
    .clk(clk),
    .rst_n(rst_n),
    .data_in(data_in),
    .control(control),
    .status(status),
    .data_out(data_out)
);
endmodule
