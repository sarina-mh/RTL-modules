// In-place max-heap sort, one sift-down comparison/swap per cycle.

// =====================================================================
// heap_sort: complete controller + datapath + top in one Verilog file.
// Pulse start while busy=0. Inputs are latched on the accepting edge.
// Reset and port conventions are preserved from the original module.
// Packed array lane i occupies bits [i*W +: W], unless stated otherwise.
// =====================================================================
// control[0]: for(k=0; k<N; k=k+1) mem[k] <= data_in[(k * W) +: W];
// control[1]: size <= N;
// control[2]: build_root <= N / 2 - 1;
// control[3]: root <= N / 2 - 1;
// control[4]: mem[root] <= mem[child];
// control[5]: mem[child] <= mem[root];
// control[6]: root <= child;
// control[7]: build_root <= build_root - 1;
// control[8]: root <= build_root - 1;
// control[9]: mem[0] <= mem[size - 1];
// control[10]: mem[size - 1] <= mem[0];
// control[11]: size <= size - 1;
// control[12]: root <= 0;
// control[13]: for(k=0; k<N; k=k+1) data_out[(k * W) +: W] <= mem[k];

// ---------------- CONTROLLER ----------------
module heap_sort_controller #
(
  parameter W = 8,
  parameter N = 8,
  parameter SIGNED = 0
)
(
  input clk,
  input rst_n,
  input start,
  input [3:0] status,
  output reg [13:0] control,
  output reg busy,
  output reg done);

reg building;
reg [2:0] state;
reg next_building;
reg next_busy;
reg next_done;
reg [2:0] next_state;

// FSM state/handshake registers; all data writes are control strobes.

always @(posedge clk) if(!rst_n) begin
  busy <= 0;
  done <= 0;
  building <= 0;
  state <= 0;
end else begin
  building <= next_building;
  busy <= next_busy;
  done <= next_done;
  state <= next_state;
end


always @(*) begin
  next_building = building;
  next_busy = busy;
  next_done = done;
  next_state = state;
  control = 0;
  begin
    next_done = 0;
    if(start && !busy) begin
      control[0] = 1'b1;
      control[1] = 1'b1;
      control[2] = 1'b1;
      control[3] = 1'b1;
      next_building = 1;
      next_state = (N == 1)? 3 : 0;
      next_busy = 1;
    end else if(busy) case(state)
      0: begin
        if(status[0] && status[1]) begin
          control[4] = 1'b1;
          control[5] = 1'b1;
          control[6] = 1'b1;
        end else next_state = 1;
      end
      1: if(building && status[2]) begin
        control[7] = 1'b1;
        control[8] = 1'b1;
        next_state = 0;
      end else begin
        next_building = 0;
        next_state = 2;
      end
      2: if(status[3]) next_state = 3;
      else begin
        control[9] = 1'b1;
        control[10] = 1'b1;
        control[11] = 1'b1;
        control[12] = 1'b1;
        next_state = 0;
      end
      3: begin
        control[13] = 1'b1;
        next_busy = 0;
        next_done = 1;
      end
      default: next_state = 0;
    endcase
  end
end

endmodule

// ---------------- DATAPATH ----------------
module heap_sort_datapath #
(
  parameter W = 8,
  parameter N = 8,
  parameter SIGNED = 0
)
(
  input clk,
  input rst_n,
  input [N*W-1:0] data_in,
  input [13:0] control,
  output [3:0] status,
  output reg [N*W-1:0] data_out);
reg [W-1:0] mem [0:N-1];
integer build_root;
integer root;
integer size;
integer child;
integer k;

function [0:0] greater;
  input [W-1:0] a;input [W-1:0] b;
  begin
    greater = (SIGNED)? $signed(a) > $signed(b) : a > b;
  end
endfunction


always @(*) begin
  child = 2 * root + 1;
  if(child + 1 < size) if(greater(mem[child + 1], mem[child])) child = child + 1;
end


// Status predicates are generated by the datapath, never by the FSM.
assign status[0] = (child < size);
assign status[1] = greater(mem[child], mem[root]);
assign status[2] = (build_root > 0);
assign status[3] = (size <= 1);

// Register-transfer operations. Later strobes retain nonblocking
// assignment priority when the same destination is written twice.

always @(posedge clk) if(!rst_n) begin
  data_out <= 0;
  build_root <= 0;
  root <= 0;
  size <= 0;
  for(k=0; k<N; k=k+1) mem[k] <= 0;
end else begin
  if(control[0]) begin
    for(k=0; k<N; k=k+1) mem[k] <= data_in[(k * W) +: W];
  end
  if(control[1]) begin
    size <= N;
  end
  if(control[2]) begin
    build_root <= N / 2 - 1;
  end
  if(control[3]) begin
    root <= N / 2 - 1;
  end
  if(control[4]) begin
    mem[root] <= mem[child];
  end
  if(control[5]) begin
    mem[child] <= mem[root];
  end
  if(control[6]) begin
    root <= child;
  end
  if(control[7]) begin
    build_root <= build_root - 1;
  end
  if(control[8]) begin
    root <= build_root - 1;
  end
  if(control[9]) begin
    mem[0] <= mem[size - 1];
  end
  if(control[10]) begin
    mem[size - 1] <= mem[0];
  end
  if(control[11]) begin
    size <= size - 1;
  end
  if(control[12]) begin
    root <= 0;
  end
  if(control[13]) begin
    for(k=0; k<N; k=k+1) data_out[(k * W) +: W] <= mem[k];
  end
end

endmodule

// ---------------- TOP ----------------
module heap_sort #
(
  parameter W = 8,
  parameter N = 8,
  parameter SIGNED = 0
)
(
  input clk,
  input rst_n,
  input start,
  input [N*W-1:0] data_in,
  output [N*W-1:0] data_out,
  output busy,
  output done);
wire [13:0] control;
wire [3:0] status;
heap_sort_controller #(.W(W), .N(N), .SIGNED(SIGNED)) controller (
    .clk(clk),
    .rst_n(rst_n),
    .start(start),
    .status(status),
    .control(control),
    .busy(busy),
    .done(done)
);
heap_sort_datapath #(.W(W), .N(N), .SIGNED(SIGNED)) datapath (
    .clk(clk),
    .rst_n(rst_n),
    .data_in(data_in),
    .control(control),
    .status(status),
    .data_out(data_out)
);
endmodule
