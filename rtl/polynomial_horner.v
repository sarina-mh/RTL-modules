// Integer polynomial c[0] + c[1]*x + ... + c[N-1]*x**(N-1).
// Horner evaluation, one coefficient per cycle. Arithmetic wraps modulo 2**W.

// =====================================================================
// polynomial_horner: complete controller + datapath + top in one Verilog file.
// Pulse start while busy=0. Inputs are latched on the accepting edge.
// Reset and port conventions are preserved from the original module.
// Packed array lane i occupies bits [i*W +: W], unless stated otherwise.
// =====================================================================
// control[0]: saved_x <= x;
// control[1]: coeff <= coefficients;
// control[2]: p <= N - 1;
// control[3]: total <= 0;
// control[4]: total <= total * saved_x + coeff[(p * W) +: W];
// control[5]: result <= total * saved_x + coeff[(p * W) +: W];
// control[6]: p <= p - 1;

// ---------------- CONTROLLER ----------------
module polynomial_horner_controller #
(
  parameter W = 16,
  parameter N = 4
)
(
  input clk,
  input rst_n,
  input start,
  input [0:0] status,
  output reg [6:0] control,
  output reg busy,
  output reg done);


reg next_busy;
reg next_done;

// FSM state/handshake registers; all data writes are control strobes.

always @(posedge clk) if(!rst_n) begin
  busy <= 0;
  done <= 0;
end else begin
  busy <= next_busy;
  done <= next_done;
end


always @(*) begin
  next_busy = busy;
  next_done = done;
  control = 0;
  begin
    next_done = 0;
    if(start && !busy) begin
      control[0] = 1'b1;
      control[1] = 1'b1;
      control[2] = 1'b1;
      control[3] = 1'b1;
      next_busy = 1;
    end else if(busy) begin
      control[4] = 1'b1;
      if(status[0]) begin
        control[5] = 1'b1;
        next_busy = 0;
        next_done = 1;
      end else control[6] = 1'b1;
    end
  end
end

endmodule

// ---------------- DATAPATH ----------------
module polynomial_horner_datapath #
(
  parameter W = 16,
  parameter N = 4
)
(
  input clk,
  input rst_n,
  input [W-1:0] x,
  input [N*W-1:0] coefficients,
  input [6:0] control,
  output [0:0] status,
  output reg [W-1:0] result);
reg [W-1:0] saved_x;
reg [W-1:0] total;
reg [N*W-1:0] coeff;
integer p;

// Status predicates are generated by the datapath, never by the FSM.
assign status[0] = (p == 0);

// Register-transfer operations. Later strobes retain nonblocking
// assignment priority when the same destination is written twice.

always @(posedge clk) if(!rst_n) begin
  result <= 0;
  saved_x <= 0;
  total <= 0;
  coeff <= 0;
  p <= 0;
end else begin
  if(control[0]) begin
    saved_x <= x;
  end
  if(control[1]) begin
    coeff <= coefficients;
  end
  if(control[2]) begin
    p <= N - 1;
  end
  if(control[3]) begin
    total <= 0;
  end
  if(control[4]) begin
    total <= total * saved_x + coeff[(p * W) +: W];
  end
  if(control[5]) begin
    result <= total * saved_x + coeff[(p * W) +: W];
  end
  if(control[6]) begin
    p <= p - 1;
  end
end

endmodule

// ---------------- TOP ----------------
module polynomial_horner #
(
  parameter W = 16,
  parameter N = 4
)
(
  input clk,
  input rst_n,
  input start,
  input [W-1:0] x,
  input [N*W-1:0] coefficients,
  output [W-1:0] result,
  output busy,
  output done);
wire [6:0] control;
wire [0:0] status;
polynomial_horner_controller #(.W(W), .N(N)) controller (
    .clk(clk),
    .rst_n(rst_n),
    .start(start),
    .status(status),
    .control(control),
    .busy(busy),
    .done(done)
);
polynomial_horner_datapath #(.W(W), .N(N)) datapath (
    .clk(clk),
    .rst_n(rst_n),
    .x(x),
    .coefficients(coefficients),
    .control(control),
    .status(status),
    .result(result)
);
endmodule
