// Sequential linear search; first match wins. index=0 when not found.

// =====================================================================
// linear_search: complete controller + datapath + top in one Verilog file.
// Pulse start while busy=0. Inputs are latched on the accepting edge.
// Reset and port conventions are preserved from the original module.
// Packed array lane i occupies bits [i*W +: W], unless stated otherwise.
// =====================================================================
// control[0]: data <= data_in;
// control[1]: key <= target;
// control[2]: p <= 0;
// control[3]: found <= 1;
// control[4]: index <= p;
// control[5]: found <= 0;
// control[6]: index <= 0;
// control[7]: p <= p + 1;

// ---------------- CONTROLLER ----------------
module linear_search_controller #
(
  parameter W = 8,
  parameter N = 8,
  parameter I = (N > 1)? $clog2(N) : 1
)
(
  input clk,
  input rst_n,
  input start,
  input [1:0] status,
  output reg [7:0] control,
  output reg busy,
  output reg done);


reg next_busy;
reg next_done;

// FSM state/handshake registers; all data writes are control strobes.

always @(posedge clk) if(!rst_n) begin
  busy <= 0;
  done <= 0;
end else begin
  busy <= next_busy;
  done <= next_done;
end


always @(*) begin
  next_busy = busy;
  next_done = done;
  control = 0;
  begin
    next_done = 0;
    if(start && !busy) begin
      control[0] = 1'b1;
      control[1] = 1'b1;
      control[2] = 1'b1;
      next_busy = 1;
    end else if(busy) begin
      if(status[0]) begin
        control[3] = 1'b1;
        control[4] = 1'b1;
        next_busy = 0;
        next_done = 1;
      end else if(status[1]) begin
        control[5] = 1'b1;
        control[6] = 1'b1;
        next_busy = 0;
        next_done = 1;
      end else control[7] = 1'b1;
    end
  end
end

endmodule

// ---------------- DATAPATH ----------------
module linear_search_datapath #
(
  parameter W = 8,
  parameter N = 8,
  parameter I = (N > 1)? $clog2(N) : 1
)
(
  input clk,
  input rst_n,
  input [N*W-1:0] data_in,
  input [W-1:0] target,
  input [7:0] control,
  output [1:0] status,
  output reg found,
  output reg [I-1:0] index);
reg [N*W-1:0] data;
reg [W-1:0] key;
integer p;

// Status predicates are generated by the datapath, never by the FSM.
assign status[0] = (data[(p * W) +: W] == key);
assign status[1] = (p == N - 1);

// Register-transfer operations. Later strobes retain nonblocking
// assignment priority when the same destination is written twice.

always @(posedge clk) if(!rst_n) begin
  found <= 0;
  index <= 0;
  data <= 0;
  key <= 0;
  p <= 0;
end else begin
  if(control[0]) begin
    data <= data_in;
  end
  if(control[1]) begin
    key <= target;
  end
  if(control[2]) begin
    p <= 0;
  end
  if(control[3]) begin
    found <= 1;
  end
  if(control[4]) begin
    index <= p;
  end
  if(control[5]) begin
    found <= 0;
  end
  if(control[6]) begin
    index <= 0;
  end
  if(control[7]) begin
    p <= p + 1;
  end
end

endmodule

// ---------------- TOP ----------------
module linear_search #
(
  parameter W = 8,
  parameter N = 8,
  parameter I = (N > 1)? $clog2(N) : 1
)
(
  input clk,
  input rst_n,
  input start,
  input [N*W-1:0] data_in,
  input [W-1:0] target,
  output found,
  output [I-1:0] index,
  output busy,
  output done);
wire [7:0] control;
wire [1:0] status;
linear_search_controller #(.W(W), .N(N), .I(I)) controller (
    .clk(clk),
    .rst_n(rst_n),
    .start(start),
    .status(status),
    .control(control),
    .busy(busy),
    .done(done)
);
linear_search_datapath #(.W(W), .N(N), .I(I)) datapath (
    .clk(clk),
    .rst_n(rst_n),
    .data_in(data_in),
    .target(target),
    .control(control),
    .status(status),
    .found(found),
    .index(index)
);
endmodule
