module exponential_fixed_helper_exp_taylor_controller #
(
  parameter W = 32,
  parameter Q = 20,
  parameter TERMS = 12
)
(
  input clk,
  input rst_n,
  input start,
  input [2:0] status,
  output reg [14:0] control,
  output reg busy,
  output reg done);
localparam MODE = 0;
localparam signed [63:0] ONE = 64'sd1 << Q;
localparam signed [63:0] PI_Q = 64'sd3373259426 >> 30 - Q;
localparam signed [63:0] MAXIMUM = (64'sd1 << W - 1) - 1;
localparam signed [63:0] MINIMUM = -(64'sd1 << W - 1);

reg next_busy;
reg next_done;

// FSM state/handshake registers; all data writes are control strobes.

always @(posedge clk) if(!rst_n) begin
  busy <= 0;
  done <= 0;
end else begin
  busy <= next_busy;
  done <= next_done;
end


always @(*) begin
  next_busy = busy;
  next_done = done;
  control = 0;
  begin
    next_done = 0;
    if(start && !busy) begin
      control[0] = 1'b1;
      control[1] = 1'b1;
      control[2] = 1'b1;
      control[3] = 1'b1;
      control[4] = 1'b1;
      next_busy = 1;
      control[5] = 1'b1;
      control[6] = 1'b1;
    end else if(busy) begin
      control[7] = 1'b1;
      control[8] = 1'b1;
      control[9] = 1'b1;
      if(status[0]) begin
        if(status[1]) begin
          control[10] = 1'b1;
          control[11] = 1'b1;
        end else if(status[2]) begin
          control[12] = 1'b1;
          control[13] = 1'b1;
        end else control[14] = 1'b1;
        next_busy = 0;
        next_done = 1;
      end
    end
  end
end

endmodule

module exponential_fixed_helper_exp_taylor_datapath #
(
  parameter W = 32,
  parameter Q = 20,
  parameter TERMS = 12
)
(
  input clk,
  input rst_n,
  input signed [W-1:0] x,
  input [14:0] control,
  output [2:0] status,
  output reg signed [W-1:0] result,
  output reg out_of_range,
  output reg overflow);
localparam MODE = 0;
localparam signed [63:0] ONE = 64'sd1 << Q;
localparam signed [63:0] PI_Q = 64'sd3373259426 >> 30 - Q;
localparam signed [63:0] MAXIMUM = (64'sd1 << W - 1) - 1;
localparam signed [63:0] MINIMUM = -(64'sd1 << W - 1);
reg signed [63:0] argument;
reg signed [63:0] square;
reg signed [63:0] term;
reg signed [63:0] total;
reg signed [63:0] next_term;
reg signed [63:0] next_total;
reg signed [127:0] product;
reg signed [127:0] scaled;
integer k;
integer denominator;

always @(*) begin
  denominator = k;
  if(MODE == 0) product = term * argument;
  else begin
    product = -term * square;
    denominator = (MODE == 1)? 2 * k * (2 * k + 1) : (2 * k - 1) * (2 * k);
  end
  scaled = product >>> Q;
  next_term = scaled / ((denominator > 0)? denominator : 1);
  next_total = total + next_term;
end


// Status predicates are generated by the datapath, never by the FSM.
assign status[0] = (k == TERMS - 1);
assign status[1] = (next_total > MAXIMUM);
assign status[2] = (next_total < MINIMUM);

// Register-transfer operations. Later strobes retain nonblocking
// assignment priority when the same destination is written twice.

always @(posedge clk) if(!rst_n) begin
  result <= 0;
  out_of_range <= 0;
  overflow <= 0;
  argument <= 0;
  square <= 0;
  term <= 0;
  total <= 0;
  k <= 1;
end else begin
  if(control[0]) begin
    argument <= x;
  end
  if(control[1]) begin
    square <= $signed(x) * $signed({ { W{ x[W - 1] } }, x }) >>> Q;
  end
  if(control[2]) begin
    term <= (MODE == 1)? $signed(x) : ONE;
  end
  if(control[3]) begin
    total <= (MODE == 1)? $signed(x) : ONE;
  end
  if(control[4]) begin
    k <= 1;
  end
  if(control[5]) begin
    overflow <= 0;
  end
  if(control[6]) begin
    out_of_range <= ($signed(x) > ((MODE == 0)? ONE : PI_Q)) || ($signed(x) < -((MODE == 0)? ONE : PI_Q));
  end
  if(control[7]) begin
    term <= next_term;
  end
  if(control[8]) begin
    total <= next_total;
  end
  if(control[9]) begin
    k <= k + 1;
  end
  if(control[10]) begin
    result <= MAXIMUM;
  end
  if(control[11]) begin
    overflow <= 1;
  end
  if(control[12]) begin
    result <= MINIMUM;
  end
  if(control[13]) begin
    overflow <= 1;
  end
  if(control[14]) begin
    result <= next_total;
  end
end

endmodule
