// exp(x) for [-4,4]: evaluate exp(x/4), then square twice.
// W<=32, Q<=20, W>=Q+4; four internal guard bits; saturating signed output.

// =====================================================================
// exponential_fixed: complete controller + datapath + top in one Verilog file.
// Pulse start while busy=0. Inputs are latched on the accepting edge.
// Reset and port conventions are preserved from the original module.
// Packed array lane i occupies bits [i*W +: W], unless stated otherwise.
// =====================================================================
// control[0]: child_start <= 0;
// control[1]: reduced <= $signed(x) <<< 2;
// control[2]: child_start <= 1;
// control[3]: overflow <= 0;
// control[4]: out_of_range <= ($signed(x) > (64'sd4 << Q)) || ($signed(x) < -(64'sd4 << Q));
// control[5]: value <= base;
// control[6]: squares <= 0;
// control[7]: value <= MAXIMUM;
// control[8]: overflow <= 1;
// control[9]: value <= product;
// control[10]: squares <= squares + 1;
// control[11]: result <= value >>> 4;

// ---------------- CONTROLLER ----------------
module exponential_fixed_controller #
(
  parameter W = 32,
  parameter Q = 20,
  parameter TERMS = 12
)
(
  input clk,
  input rst_n,
  input start,
  input [2:0] status,
  output reg [11:0] control,
  output reg busy,
  output reg done);
localparam signed [127:0] MAXIMUM = (128'sd1 << W - 1) - 1 << 4;
reg [1:0] state;
reg next_busy;
reg next_done;
reg [1:0] next_state;

// FSM state/handshake registers; all data writes are control strobes.

always @(posedge clk) if(!rst_n) begin
  busy <= 0;
  done <= 0;
  state <= 0;
end else begin
  busy <= next_busy;
  done <= next_done;
  state <= next_state;
end


always @(*) begin
  next_busy = busy;
  next_done = done;
  next_state = state;
  control = 0;
  begin
    next_done = 0;
    control[0] = 1'b1;
    if(start && !busy) begin
      control[1] = 1'b1;
      control[2] = 1'b1;
      next_busy = 1;
      next_state = 0;
      control[3] = 1'b1;
      control[4] = 1'b1;
    end else if(busy) case(state)
      0: if(status[0]) begin
        control[5] = 1'b1;
        control[6] = 1'b1;
        next_state = 1;
      end
      1: begin
        if(status[1]) begin
          control[7] = 1'b1;
          control[8] = 1'b1;
        end else control[9] = 1'b1;
        control[10] = 1'b1;
        if(status[2]) next_state = 2;
      end
      2: begin
        control[11] = 1'b1;
        next_busy = 0;
        next_done = 1;
      end
      default: next_state = 0;
    endcase
  end
end

endmodule

// ---------------- DATAPATH ----------------
module exponential_fixed_datapath #
(
  parameter W = 32,
  parameter Q = 20,
  parameter TERMS = 12
)
(
  input clk,
  input rst_n,
  input signed [W-1:0] x,
  input [11:0] control,
  output [2:0] status,
  output reg signed [W-1:0] result,
  output reg out_of_range,
  output reg overflow);
localparam signed [127:0] MAXIMUM = (128'sd1 << W - 1) - 1 << 4;
reg signed [31:0] reduced;
reg child_start;
wire child_busy;
wire child_done;
wire child_range;
wire child_overflow;
wire signed [31:0] base;
reg signed [63:0] value;
reg signed [127:0] product;
integer squares;

exponential_fixed_helper_exp_taylor
#(
  32,
  Q + 4,
  TERMS
)
core
(
  clk,
  rst_n,
  child_start,
  reduced,
  base,
  child_busy,
  child_done,
  child_range,
  child_overflow
);


always @(*) product = value * value >>> Q + 4;


// Status predicates are generated by the datapath, never by the FSM.
assign status[0] = child_done;
assign status[1] = (product > MAXIMUM);
assign status[2] = (squares == 1);

// Register-transfer operations. Later strobes retain nonblocking
// assignment priority when the same destination is written twice.

always @(posedge clk) if(!rst_n) begin
  result <= 0;
  out_of_range <= 0;
  overflow <= 0;
  reduced <= 0;
  child_start <= 0;
  value <= 0;
  squares <= 0;
end else begin
  if(control[0]) begin
    child_start <= 0;
  end
  if(control[1]) begin
    reduced <= $signed(x) <<< 2;
  end
  if(control[2]) begin
    child_start <= 1;
  end
  if(control[3]) begin
    overflow <= 0;
  end
  if(control[4]) begin
    out_of_range <= ($signed(x) > (64'sd4 << Q)) || ($signed(x) < -(64'sd4 << Q));
  end
  if(control[5]) begin
    value <= base;
  end
  if(control[6]) begin
    squares <= 0;
  end
  if(control[7]) begin
    value <= MAXIMUM;
  end
  if(control[8]) begin
    overflow <= 1;
  end
  if(control[9]) begin
    value <= product;
  end
  if(control[10]) begin
    squares <= squares + 1;
  end
  if(control[11]) begin
    result <= value >>> 4;
  end
end

endmodule

