// Integer bucket sort: high key bits select a bucket; each bucket is insertion
// sorted, then concatenated. 1 <= BITS <= W; storage is N * 2**BITS words.

// =====================================================================
// bucket_sort: complete controller + datapath + top in one Verilog file.
// Pulse start while busy=0. Inputs are latched on the accepting edge.
// Reset and port conventions are preserved from the original module.
// Packed array lane i occupies bits [i*W +: W], unless stated otherwise.
// =====================================================================
// control[0]: data <= data_in;
// control[1]: p <= 0;
// control[2]: bucket <= 0;
// control[3]: out_index <= 0;
// control[4]: for(k=0; k<B; k=k+1) counts[k] <= 0;
// control[5]: buckets[destination * N + counts[destination]] <= data[(p * W) +: W];
// control[6]: counts[destination] <= counts[destination] + 1;
// control[7]: i <= 1;
// control[8]: p <= p + 1;
// control[9]: p <= 0;
// control[10]: key <= buckets[bucket * N + i];
// control[11]: j <= i - 1;
// control[12]: buckets[bucket * N + j + 1] <= buckets[bucket * N + j];
// control[13]: j <= j - 1;
// control[14]: buckets[bucket * N + j + 1] <= key;
// control[15]: i <= i + 1;
// control[16]: data_out[(out_index * W) +: W] <= buckets[bucket * N + p];
// control[17]: out_index <= out_index + 1;
// control[18]: p <= p + 1;
// control[19]: bucket <= bucket + 1;
// control[20]: i <= 1;

// ---------------- CONTROLLER ----------------
module bucket_sort_controller #
(
  parameter W = 8,
  parameter N = 8,
  parameter SIGNED = 0,
  parameter BITS = (W > 1)? 2 : 1
)
(
  input clk,
  input rst_n,
  input start,
  input [5:0] status,
  output reg [20:0] control,
  output reg busy,
  output reg done);
localparam B = 1 << BITS;
reg [2:0] state;
reg next_busy;
reg next_done;
reg [2:0] next_state;

// FSM state/handshake registers; all data writes are control strobes.

always @(posedge clk) if(!rst_n) begin
  busy <= 0;
  done <= 0;
  state <= 0;
end else begin
  busy <= next_busy;
  done <= next_done;
  state <= next_state;
end


always @(*) begin
  next_busy = busy;
  next_done = done;
  next_state = state;
  control = 0;
  begin
    next_done = 0;
    if(start && !busy) begin
      control[0] = 1'b1;
      control[1] = 1'b1;
      control[2] = 1'b1;
      control[3] = 1'b1;
      next_state = 0;
      next_busy = 1;
      control[4] = 1'b1;
    end else if(busy) case(state)
      0: begin
        control[5] = 1'b1;
        control[6] = 1'b1;
        if(status[0]) begin
          control[7] = 1'b1;
          next_state = 1;
        end else control[8] = 1'b1;
      end
      1: if(status[1]) begin
        control[9] = 1'b1;
        next_state = 4;
      end else begin
        control[10] = 1'b1;
        control[11] = 1'b1;
        next_state = 2;
      end
      2: if(status[2] && status[3]) begin
        control[12] = 1'b1;
        control[13] = 1'b1;
      end else begin
        control[14] = 1'b1;
        control[15] = 1'b1;
        next_state = 1;
      end
      4: if(status[4]) begin
        control[16] = 1'b1;
        control[17] = 1'b1;
        control[18] = 1'b1;
      end else if(status[5]) next_state = 5;
      else begin
        control[19] = 1'b1;
        control[20] = 1'b1;
        next_state = 1;
      end
      5: begin
        next_busy = 0;
        next_done = 1;
      end
      default: next_state = 0;
    endcase
  end
end

endmodule

// ---------------- DATAPATH ----------------
module bucket_sort_datapath #
(
  parameter W = 8,
  parameter N = 8,
  parameter SIGNED = 0,
  parameter BITS = (W > 1)? 2 : 1
)
(
  input clk,
  input rst_n,
  input [N*W-1:0] data_in,
  input [20:0] control,
  output [5:0] status,
  output reg [N*W-1:0] data_out);
localparam B = 1 << BITS;
reg [W-1:0] buckets [0:B*N-1];
reg [W-1:0] key;
reg signed [31:0] counts [0:B-1];
reg [N*W-1:0] data;
integer bucket;
integer p;
integer i;
integer j;
integer out_index;
integer k;
wire [W-1:0] biased;
assign biased = data[(p * W) +: W] ^ ((SIGNED)? 1 << W - 1 : 0);
wire [BITS-1:0] destination;
assign destination = biased[(W - 1) -: BITS];
wire greater;
assign greater = (SIGNED)? $signed(buckets[bucket * N + ((j >= 0)? j : 0)]) > $signed(key) : buckets[bucket * N + ((j >= 0)? j : 0)] > key;

// Status predicates are generated by the datapath, never by the FSM.
assign status[0] = (p == N - 1);
assign status[1] = (i >= counts[bucket]);
assign status[2] = (j >= 0);
assign status[3] = greater;
assign status[4] = (p < counts[bucket]);
assign status[5] = (bucket == B - 1);

// Register-transfer operations. Later strobes retain nonblocking
// assignment priority when the same destination is written twice.

always @(posedge clk) if(!rst_n) begin
  data_out <= 0;
  data <= 0;
  key <= 0;
  bucket <= 0;
  p <= 0;
  i <= 0;
  j <= 0;
  out_index <= 0;
  for(k=0; k<B; k=k+1) counts[k] <= 0;
  for(k=0; k<B*N; k=k+1) buckets[k] <= 0;
end else begin
  if(control[0]) begin
    data <= data_in;
  end
  if(control[1]) begin
    p <= 0;
  end
  if(control[2]) begin
    bucket <= 0;
  end
  if(control[3]) begin
    out_index <= 0;
  end
  if(control[4]) begin
    for(k=0; k<B; k=k+1) counts[k] <= 0;
  end
  if(control[5]) begin
    buckets[destination * N + counts[destination]] <= data[(p * W) +: W];
  end
  if(control[6]) begin
    counts[destination] <= counts[destination] + 1;
  end
  if(control[7]) begin
    i <= 1;
  end
  if(control[8]) begin
    p <= p + 1;
  end
  if(control[9]) begin
    p <= 0;
  end
  if(control[10]) begin
    key <= buckets[bucket * N + i];
  end
  if(control[11]) begin
    j <= i - 1;
  end
  if(control[12]) begin
    buckets[bucket * N + j + 1] <= buckets[bucket * N + j];
  end
  if(control[13]) begin
    j <= j - 1;
  end
  if(control[14]) begin
    buckets[bucket * N + j + 1] <= key;
  end
  if(control[15]) begin
    i <= i + 1;
  end
  if(control[16]) begin
    data_out[(out_index * W) +: W] <= buckets[bucket * N + p];
  end
  if(control[17]) begin
    out_index <= out_index + 1;
  end
  if(control[18]) begin
    p <= p + 1;
  end
  if(control[19]) begin
    bucket <= bucket + 1;
  end
  if(control[20]) begin
    i <= 1;
  end
end

endmodule

// ---------------- TOP ----------------
module bucket_sort #
(
  parameter W = 8,
  parameter N = 8,
  parameter SIGNED = 0,
  parameter BITS = (W > 1)? 2 : 1
)
(
  input clk,
  input rst_n,
  input start,
  input [N*W-1:0] data_in,
  output [N*W-1:0] data_out,
  output busy,
  output done);
wire [20:0] control;
wire [5:0] status;
bucket_sort_controller #(.W(W), .N(N), .SIGNED(SIGNED), .BITS(BITS)) controller (
    .clk(clk),
    .rst_n(rst_n),
    .start(start),
    .status(status),
    .control(control),
    .busy(busy),
    .done(done)
);
bucket_sort_datapath #(.W(W), .N(N), .SIGNED(SIGNED), .BITS(BITS)) datapath (
    .clk(clk),
    .rst_n(rst_n),
    .data_in(data_in),
    .control(control),
    .status(status),
    .data_out(data_out)
);
endmodule
