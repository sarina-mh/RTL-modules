// Module: iterative_divider. Original group: algorithms.
// W restoring steps. /0 completes immediately with quotient all ones.

// =====================================================================
// iterative_divider: complete controller + datapath + top in one Verilog file.
// Pulse start while busy=0. Inputs are latched on the accepting edge.
// Reset and port conventions are preserved from the original module.
// Packed array lane i occupies bits [i*W +: W], unless stated otherwise.
// =====================================================================
// control[0]: divide_by_zero <= b == 0;
// control[1]: quotient <= { W{ 1'b1 } };
// control[2]: remainder <= a;
// control[3]: dividend <= a;
// control[4]: divisor <= b;
// control[5]: q <= 0;
// control[6]: rem_reg <= 0;
// control[7]: left <= W;
// control[8]: dividend <= dividend << 1;
// control[9]: q <= next_q;
// control[10]: rem_reg <= next_rem;
// control[11]: left <= left - 1;
// control[12]: quotient <= next_q;
// control[13]: remainder <= next_rem[W-1:0];

// ---------------- CONTROLLER ----------------
module iterative_divider_controller #
(
  parameter W = 8
)
(
  input clk,
  input rst_n,
  input start,
  input [1:0] status,
  output reg [13:0] control,
  output reg busy,
  output reg done);


reg next_busy;
reg next_done;

// FSM state/handshake registers; all data writes are control strobes.

always @(posedge clk) if(!rst_n) begin
  busy <= 0;
  done <= 0;
end else begin
  busy <= next_busy;
  done <= next_done;
end


always @(*) begin
  next_busy = busy;
  next_done = done;
  control = 0;
  begin
    next_done = 0;
    if(start && !busy) begin
      control[0] = 1'b1;
      if(status[0]) begin
        control[1] = 1'b1;
        control[2] = 1'b1;
        next_done = 1;
      end else begin
        control[3] = 1'b1;
        control[4] = 1'b1;
        control[5] = 1'b1;
        control[6] = 1'b1;
        control[7] = 1'b1;
        next_busy = 1;
      end
    end else if(busy) begin
      control[8] = 1'b1;
      control[9] = 1'b1;
      control[10] = 1'b1;
      control[11] = 1'b1;
      if(status[1]) begin
        control[12] = 1'b1;
        control[13] = 1'b1;
        next_busy = 0;
        next_done = 1;
      end
    end
  end
end

endmodule

// ---------------- DATAPATH ----------------
module iterative_divider_datapath #
(
  parameter W = 8
)
(
  input clk,
  input rst_n,
  input [W-1:0] a,
  input [W-1:0] b,
  input [13:0] control,
  output [1:0] status,
  output reg [W-1:0] quotient,
  output reg [W-1:0] remainder,
  output reg divide_by_zero);
reg [W-1:0] dividend;
reg [W-1:0] divisor;
reg [W-1:0] q;
reg [W:0] rem_reg;
reg [W:0] next_rem;
reg [W-1:0] next_q;
integer left;

always @(*) begin
  next_rem = { rem_reg[W-1:0], dividend[W - 1] };
  next_q = q << 1;
  if(next_rem >= { 1'b0, divisor }) begin
    next_rem = next_rem - divisor;
    next_q[0] = 1;
  end
end


// Status predicates are generated by the datapath, never by the FSM.
assign status[0] = (b == 0);
assign status[1] = (left == 1);

// Register-transfer operations. Later strobes retain nonblocking
// assignment priority when the same destination is written twice.

always @(posedge clk) if(!rst_n) begin
  quotient <= 0;
  remainder <= 0;
  divide_by_zero <= 0;
  dividend <= 0;
  divisor <= 0;
  q <= 0;
  rem_reg <= 0;
  left <= 0;
end else begin
  if(control[0]) begin
    divide_by_zero <= b == 0;
  end
  if(control[1]) begin
    quotient <= { W{ 1'b1 } };
  end
  if(control[2]) begin
    remainder <= a;
  end
  if(control[3]) begin
    dividend <= a;
  end
  if(control[4]) begin
    divisor <= b;
  end
  if(control[5]) begin
    q <= 0;
  end
  if(control[6]) begin
    rem_reg <= 0;
  end
  if(control[7]) begin
    left <= W;
  end
  if(control[8]) begin
    dividend <= dividend << 1;
  end
  if(control[9]) begin
    q <= next_q;
  end
  if(control[10]) begin
    rem_reg <= next_rem;
  end
  if(control[11]) begin
    left <= left - 1;
  end
  if(control[12]) begin
    quotient <= next_q;
  end
  if(control[13]) begin
    remainder <= next_rem[W-1:0];
  end
end

endmodule

// ---------------- TOP ----------------
module iterative_divider #
(
  parameter W = 8
)
(
  input clk,
  input rst_n,
  input start,
  input [W-1:0] a,
  input [W-1:0] b,
  output [W-1:0] quotient,
  output [W-1:0] remainder,
  output busy,
  output done,
  output divide_by_zero);
wire [13:0] control;
wire [1:0] status;
iterative_divider_controller #(.W(W)) controller (
    .clk(clk),
    .rst_n(rst_n),
    .start(start),
    .status(status),
    .control(control),
    .busy(busy),
    .done(done)
);
iterative_divider_datapath #(.W(W)) datapath (
    .clk(clk),
    .rst_n(rst_n),
    .a(a),
    .b(b),
    .control(control),
    .status(status),
    .quotient(quotient),
    .remainder(remainder),
    .divide_by_zero(divide_by_zero)
);
endmodule
