// Module: insertion_sort. Original group: algorithms.
// Insertion sort: load a key, shift one predecessor per cycle, then insert.

// =====================================================================
// insertion_sort: complete controller + datapath + top in one Verilog file.
// Pulse start while busy=0. Inputs are latched on the accepting edge.
// Reset and port conventions are preserved from the original module.
// Packed array lane i occupies bits [i*W +: W], unless stated otherwise.
// =====================================================================
// control[0]: for(k=0; k<N; k=k+1) mem[k] <= data_in[(k * W) +: W];
// control[1]: i <= 1;
// control[2]: key <= mem[i];
// control[3]: j <= i - 1;
// control[4]: mem[j + 1] <= mem[j];
// control[5]: j <= j - 1;
// control[6]: mem[j + 1] <= key;
// control[7]: i <= i + 1;
// control[8]: for(k=0; k<N; k=k+1) data_out[(k * W) +: W] <= mem[k];

// ---------------- CONTROLLER ----------------
module insertion_sort_controller #
(
  parameter W = 8,
  parameter N = 8,
  parameter SIGNED = 0
)
(
  input clk,
  input rst_n,
  input start,
  input [2:0] status,
  output reg [8:0] control,
  output reg busy,
  output reg done);

reg [1:0] phase;
reg next_busy;
reg next_done;
reg [1:0] next_phase;

// FSM state/handshake registers; all data writes are control strobes.

always @(posedge clk) if(!rst_n) begin
  busy <= 0;
  done <= 0;
  phase <= 0;
end else begin
  busy <= next_busy;
  done <= next_done;
  phase <= next_phase;
end


always @(*) begin
  next_busy = busy;
  next_done = done;
  next_phase = phase;
  control = 0;
  begin
    next_done = 0;
    if(start && !busy) begin
      control[0] = 1'b1;
      next_busy = 1;
      control[1] = 1'b1;
      next_phase = (N == 1)? 2 : 0;
    end else if(busy) case(phase)
      0: begin
        control[2] = 1'b1;
        control[3] = 1'b1;
        next_phase = 1;
      end
      1: begin
        if(status[0] && status[1]) begin
          control[4] = 1'b1;
          control[5] = 1'b1;
        end else begin
          control[6] = 1'b1;
          if(status[2]) next_phase = 2;
          else begin
            control[7] = 1'b1;
            next_phase = 0;
          end
        end
      end
      2: begin
        control[8] = 1'b1;
        next_busy = 0;
        next_done = 1;
      end
      default: next_phase = 0;
    endcase
  end
end

endmodule

// ---------------- DATAPATH ----------------
module insertion_sort_datapath #
(
  parameter W = 8,
  parameter N = 8,
  parameter SIGNED = 0
)
(
  input clk,
  input rst_n,
  input [N*W-1:0] data_in,
  input [8:0] control,
  output [2:0] status,
  output reg [N*W-1:0] data_out);
reg [W-1:0] mem [0:N-1];
reg [W-1:0] key;
integer i;
integer j;
integer k;
wire greater;
assign greater = (SIGNED)? $signed(mem[j]) > $signed(key) : mem[j] > key;

// Status predicates are generated by the datapath, never by the FSM.
assign status[0] = (j >= 0);
assign status[1] = greater;
assign status[2] = (i == N - 1);

// Register-transfer operations. Later strobes retain nonblocking
// assignment priority when the same destination is written twice.

always @(posedge clk) if(!rst_n) begin
  data_out <= 0;
  i <= 0;
  j <= 0;
  key <= 0;
  for(k=0; k<N; k=k+1) mem[k] <= 0;
end else begin
  if(control[0]) begin
    for(k=0; k<N; k=k+1) mem[k] <= data_in[(k * W) +: W];
  end
  if(control[1]) begin
    i <= 1;
  end
  if(control[2]) begin
    key <= mem[i];
  end
  if(control[3]) begin
    j <= i - 1;
  end
  if(control[4]) begin
    mem[j + 1] <= mem[j];
  end
  if(control[5]) begin
    j <= j - 1;
  end
  if(control[6]) begin
    mem[j + 1] <= key;
  end
  if(control[7]) begin
    i <= i + 1;
  end
  if(control[8]) begin
    for(k=0; k<N; k=k+1) data_out[(k * W) +: W] <= mem[k];
  end
end

endmodule

// ---------------- TOP ----------------
module insertion_sort #
(
  parameter W = 8,
  parameter N = 8,
  parameter SIGNED = 0
)
(
  input clk,
  input rst_n,
  input start,
  input [N*W-1:0] data_in,
  output [N*W-1:0] data_out,
  output busy,
  output done);
wire [8:0] control;
wire [2:0] status;
insertion_sort_controller #(.W(W), .N(N), .SIGNED(SIGNED)) controller (
    .clk(clk),
    .rst_n(rst_n),
    .start(start),
    .status(status),
    .control(control),
    .busy(busy),
    .done(done)
);
insertion_sort_datapath #(.W(W), .N(N), .SIGNED(SIGNED)) datapath (
    .clk(clk),
    .rst_n(rst_n),
    .data_in(data_in),
    .control(control),
    .status(status),
    .data_out(data_out)
);
endmodule
