// Sequential dot product. AW>=2*W+ceil(log2(N)) retains full precision.

// =====================================================================
// dot_product: complete controller + datapath + top in one Verilog file.
// Pulse start while busy=0. Inputs are latched on the accepting edge.
// Reset and port conventions are preserved from the original module.
// Packed array lane i occupies bits [i*W +: W], unless stated otherwise.
// =====================================================================
// control[0]: sa <= a;
// control[1]: sb <= b;
// control[2]: total <= 0;
// control[3]: p <= 0;
// control[4]: total <= total + extended;
// control[5]: result <= total + extended;
// control[6]: p <= p + 1;

// ---------------- CONTROLLER ----------------
module dot_product_controller #
(
  parameter W = 8,
  parameter N = 8,
  parameter SIGNED = 0,
  parameter AW = 2 * W + $clog2(N)
)
(
  input clk,
  input rst_n,
  input start,
  input [0:0] status,
  output reg [6:0] control,
  output reg busy,
  output reg done);


reg next_busy;
reg next_done;

// FSM state/handshake registers; all data writes are control strobes.

always @(posedge clk) if(!rst_n) begin
  busy <= 0;
  done <= 0;
end else begin
  busy <= next_busy;
  done <= next_done;
end


always @(*) begin
  next_busy = busy;
  next_done = done;
  control = 0;
  begin
    next_done = 0;
    if(start && !busy) begin
      control[0] = 1'b1;
      control[1] = 1'b1;
      control[2] = 1'b1;
      control[3] = 1'b1;
      next_busy = 1;
    end else if(busy) begin
      control[4] = 1'b1;
      if(status[0]) begin
        control[5] = 1'b1;
        next_busy = 0;
        next_done = 1;
      end else control[6] = 1'b1;
    end
  end
end

endmodule

// ---------------- DATAPATH ----------------
module dot_product_datapath #
(
  parameter W = 8,
  parameter N = 8,
  parameter SIGNED = 0,
  parameter AW = 2 * W + $clog2(N)
)
(
  input clk,
  input rst_n,
  input [N*W-1:0] a,
  input [N*W-1:0] b,
  input [6:0] control,
  output [0:0] status,
  output reg [AW-1:0] result);
reg [N*W-1:0] sa;
reg [N*W-1:0] sb;
reg [AW-1:0] total;
integer p;
wire [W-1:0] x;
assign x = sa[(p * W) +: W];
wire [W-1:0] y;
assign y = sb[(p * W) +: W];
wire [2*W-1:0] product;
wire [AW-1:0] extended;

generate if(SIGNED) begin : signed_math
  assign product = $signed(x) * $signed(y);
  assign extended = $signed(product);
end else begin : unsigned_math
  assign product = x * y;
  assign extended = product;
end
endgenerate


// Status predicates are generated by the datapath, never by the FSM.
assign status[0] = (p == N - 1);

// Register-transfer operations. Later strobes retain nonblocking
// assignment priority when the same destination is written twice.

always @(posedge clk) if(!rst_n) begin
  sa <= 0;
  sb <= 0;
  total <= 0;
  result <= 0;
  p <= 0;
end else begin
  if(control[0]) begin
    sa <= a;
  end
  if(control[1]) begin
    sb <= b;
  end
  if(control[2]) begin
    total <= 0;
  end
  if(control[3]) begin
    p <= 0;
  end
  if(control[4]) begin
    total <= total + extended;
  end
  if(control[5]) begin
    result <= total + extended;
  end
  if(control[6]) begin
    p <= p + 1;
  end
end

endmodule

// ---------------- TOP ----------------
module dot_product #
(
  parameter W = 8,
  parameter N = 8,
  parameter SIGNED = 0,
  parameter AW = 2 * W + $clog2(N)
)
(
  input clk,
  input rst_n,
  input start,
  input [N*W-1:0] a,
  input [N*W-1:0] b,
  output [AW-1:0] result,
  output busy,
  output done);
wire [6:0] control;
wire [0:0] status;
dot_product_controller #(.W(W), .N(N), .SIGNED(SIGNED), .AW(AW)) controller (
    .clk(clk),
    .rst_n(rst_n),
    .start(start),
    .status(status),
    .control(control),
    .busy(busy),
    .done(done)
);
dot_product_datapath #(.W(W), .N(N), .SIGNED(SIGNED), .AW(AW)) datapath (
    .clk(clk),
    .rst_n(rst_n),
    .a(a),
    .b(b),
    .control(control),
    .status(status),
    .result(result)
);
endmodule
