// Unsigned n!; wraps modulo 2**W and reports any overflow. 0! = 1.

// =====================================================================
// factorial: complete controller + datapath + top in one Verilog file.
// Pulse start while busy=0. Inputs are latched on the accepting edge.
// Reset and port conventions are preserved from the original module.
// Packed array lane i occupies bits [i*W +: W], unless stated otherwise.
// =====================================================================
// control[0]: total <= 1;
// control[1]: limit <= n;
// control[2]: p <= 1;
// control[3]: overflow <= 0;
// control[4]: result <= total;
// control[5]: total <= product[W-1:0];
// control[6]: overflow <= 1;
// control[7]: p <= p + 1'b1;

// ---------------- CONTROLLER ----------------
module factorial_controller #
(
  parameter W = 32,
  parameter B = 8
)
(
  input clk,
  input rst_n,
  input start,
  input [1:0] status,
  output reg [7:0] control,
  output reg busy,
  output reg done);


reg next_busy;
reg next_done;

// FSM state/handshake registers; all data writes are control strobes.

always @(posedge clk) if(!rst_n) begin
  busy <= 0;
  done <= 0;
end else begin
  busy <= next_busy;
  done <= next_done;
end


always @(*) begin
  next_busy = busy;
  next_done = done;
  control = 0;
  begin
    next_done = 0;
    if(start && !busy) begin
      control[0] = 1'b1;
      control[1] = 1'b1;
      control[2] = 1'b1;
      next_busy = 1;
      control[3] = 1'b1;
    end else if(busy) begin
      if(status[0]) begin
        control[4] = 1'b1;
        next_busy = 0;
        next_done = 1;
      end else begin
        control[5] = 1'b1;
        if(status[1]) control[6] = 1'b1;
        control[7] = 1'b1;
      end
    end
  end
end

endmodule

// ---------------- DATAPATH ----------------
module factorial_datapath #
(
  parameter W = 32,
  parameter B = 8
)
(
  input clk,
  input rst_n,
  input [B-1:0] n,
  input [7:0] control,
  output [1:0] status,
  output reg [W-1:0] result,
  output reg overflow);
reg [W-1:0] total;
reg [B-1:0] limit;
reg [B:0] p;
wire [W+B:0] product;
assign product = total * p;

// Status predicates are generated by the datapath, never by the FSM.
assign status[0] = (p > limit);
assign status[1] = (|product[W+B:W]);

// Register-transfer operations. Later strobes retain nonblocking
// assignment priority when the same destination is written twice.

always @(posedge clk) if(!rst_n) begin
  result <= 0;
  overflow <= 0;
  total <= 1;
  limit <= 0;
  p <= 1;
end else begin
  if(control[0]) begin
    total <= 1;
  end
  if(control[1]) begin
    limit <= n;
  end
  if(control[2]) begin
    p <= 1;
  end
  if(control[3]) begin
    overflow <= 0;
  end
  if(control[4]) begin
    result <= total;
  end
  if(control[5]) begin
    total <= product[W-1:0];
  end
  if(control[6]) begin
    overflow <= 1;
  end
  if(control[7]) begin
    p <= p + 1'b1;
  end
end

endmodule

// ---------------- TOP ----------------
module factorial #
(
  parameter W = 32,
  parameter B = 8
)
(
  input clk,
  input rst_n,
  input start,
  input [B-1:0] n,
  output [W-1:0] result,
  output busy,
  output done,
  output overflow);
wire [7:0] control;
wire [1:0] status;
factorial_controller #(.W(W), .B(B)) controller (
    .clk(clk),
    .rst_n(rst_n),
    .start(start),
    .status(status),
    .control(control),
    .busy(busy),
    .done(done)
);
factorial_datapath #(.W(W), .B(B)) datapath (
    .clk(clk),
    .rst_n(rst_n),
    .n(n),
    .control(control),
    .status(status),
    .result(result),
    .overflow(overflow)
);
endmodule
