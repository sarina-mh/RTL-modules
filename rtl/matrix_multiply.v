// Row-major A[R,K] times B[K,C]. One multiply-accumulate per clock.
// Signed/unsigned full-precision output by default; lane (r*C+c) is result[r,c].

// =====================================================================
// matrix_multiply: complete controller + datapath + top in one Verilog file.
// Pulse start while busy=0. Inputs are latched on the accepting edge.
// Reset and port conventions are preserved from the original module.
// Packed array lane i occupies bits [i*W +: W], unless stated otherwise.
// =====================================================================
// control[0]: sa <= a;
// control[1]: sb <= b;
// control[2]: row <= 0;
// control[3]: col <= 0;
// control[4]: term <= 0;
// control[5]: total <= 0;
// control[6]: result[((row * C + col) * AW) +: AW] <= total + extended;
// control[7]: total <= 0;
// control[8]: term <= 0;
// control[9]: col <= 0;
// control[10]: row <= row + 1;
// control[11]: col <= col + 1;
// control[12]: total <= total + extended;
// control[13]: term <= term + 1;

// ---------------- CONTROLLER ----------------
module matrix_multiply_controller #
(
  parameter W = 8,
  parameter R = 2,
  parameter K = 3,
  parameter C = 2,
  parameter SIGNED = 0,
  parameter AW = 2 * W + $clog2(K)
)
(
  input clk,
  input rst_n,
  input start,
  input [2:0] status,
  output reg [13:0] control,
  output reg busy,
  output reg done);


reg next_busy;
reg next_done;

// FSM state/handshake registers; all data writes are control strobes.

always @(posedge clk) if(!rst_n) begin
  busy <= 0;
  done <= 0;
end else begin
  busy <= next_busy;
  done <= next_done;
end


always @(*) begin
  next_busy = busy;
  next_done = done;
  control = 0;
  begin
    next_done = 0;
    if(start && !busy) begin
      control[0] = 1'b1;
      control[1] = 1'b1;
      control[2] = 1'b1;
      control[3] = 1'b1;
      control[4] = 1'b1;
      control[5] = 1'b1;
      next_busy = 1;
    end else if(busy) begin
      if(status[0]) begin
        control[6] = 1'b1;
        control[7] = 1'b1;
        control[8] = 1'b1;
        if(status[1]) begin
          control[9] = 1'b1;
          if(status[2]) begin
            next_busy = 0;
            next_done = 1;
          end else control[10] = 1'b1;
        end else control[11] = 1'b1;
      end else begin
        control[12] = 1'b1;
        control[13] = 1'b1;
      end
    end
  end
end

endmodule

// ---------------- DATAPATH ----------------
module matrix_multiply_datapath #
(
  parameter W = 8,
  parameter R = 2,
  parameter K = 3,
  parameter C = 2,
  parameter SIGNED = 0,
  parameter AW = 2 * W + $clog2(K)
)
(
  input clk,
  input rst_n,
  input [R*K*W-1:0] a,
  input [K*C*W-1:0] b,
  input [13:0] control,
  output [2:0] status,
  output reg [R*C*AW-1:0] result);
reg [R*K*W-1:0] sa;
reg [K*C*W-1:0] sb;
integer row;
integer col;
integer term;
reg [AW-1:0] total;
wire [W-1:0] x;
assign x = sa[((row * K + term) * W) +: W];
wire [W-1:0] y;
assign y = sb[((term * C + col) * W) +: W];
wire [2*W-1:0] product;
wire [AW-1:0] extended;

generate if(SIGNED) begin : signed_math
  assign product = $signed(x) * $signed(y);
  assign extended = $signed(product);
end else begin : unsigned_math
  assign product = x * y;
  assign extended = product;
end
endgenerate


// Status predicates are generated by the datapath, never by the FSM.
assign status[0] = (term == K - 1);
assign status[1] = (col == C - 1);
assign status[2] = (row == R - 1);

// Register-transfer operations. Later strobes retain nonblocking
// assignment priority when the same destination is written twice.

always @(posedge clk) if(!rst_n) begin
  sa <= 0;
  sb <= 0;
  result <= 0;
  total <= 0;
  row <= 0;
  col <= 0;
  term <= 0;
end else begin
  if(control[0]) begin
    sa <= a;
  end
  if(control[1]) begin
    sb <= b;
  end
  if(control[2]) begin
    row <= 0;
  end
  if(control[3]) begin
    col <= 0;
  end
  if(control[4]) begin
    term <= 0;
  end
  if(control[5]) begin
    total <= 0;
  end
  if(control[6]) begin
    result[((row * C + col) * AW) +: AW] <= total + extended;
  end
  if(control[7]) begin
    total <= 0;
  end
  if(control[8]) begin
    term <= 0;
  end
  if(control[9]) begin
    col <= 0;
  end
  if(control[10]) begin
    row <= row + 1;
  end
  if(control[11]) begin
    col <= col + 1;
  end
  if(control[12]) begin
    total <= total + extended;
  end
  if(control[13]) begin
    term <= term + 1;
  end
end

endmodule

// ---------------- TOP ----------------
module matrix_multiply #
(
  parameter W = 8,
  parameter R = 2,
  parameter K = 3,
  parameter C = 2,
  parameter SIGNED = 0,
  parameter AW = 2 * W + $clog2(K)
)
(
  input clk,
  input rst_n,
  input start,
  input [R*K*W-1:0] a,
  input [K*C*W-1:0] b,
  output [R*C*AW-1:0] result,
  output busy,
  output done);
wire [13:0] control;
wire [2:0] status;
matrix_multiply_controller #(.W(W), .R(R), .K(K), .C(C), .SIGNED(SIGNED), .AW(AW)) controller (
    .clk(clk),
    .rst_n(rst_n),
    .start(start),
    .status(status),
    .control(control),
    .busy(busy),
    .done(done)
);
matrix_multiply_datapath #(.W(W), .R(R), .K(K), .C(C), .SIGNED(SIGNED), .AW(AW)) datapath (
    .clk(clk),
    .rst_n(rst_n),
    .a(a),
    .b(b),
    .control(control),
    .status(status),
    .result(result)
);
endmodule
