// Finite real Fourier series on theta=2*pi*phase/64:
// y=c[0]+sum(h=1..H){c[h]*cos(h*theta)+s[h]*sin(h*theta)}.
// c[0] is the actual constant term (predivide a0 by 2 if using that convention).
// Signed fixed-point coefficients/results; H>=0; sine coefficient s[0] ignored.
// One harmonic MAC per cycle; output saturates and sets overflow.

// =====================================================================
// fourier_series: complete controller + datapath + top in one Verilog file.
// Pulse start while busy=0. Inputs are latched on the accepting edge.
// Reset and port conventions are preserved from the original module.
// Packed array lane i occupies bits [i*W +: W], unless stated otherwise.
// =====================================================================
// control[0]: c <= cosine_coefficients;
// control[1]: s <= sine_coefficients;
// control[2]: saved_phase <= phase;
// control[3]: harmonic <= 1;
// control[4]: total <= $signed(cosine_coefficients[0 +: W]);
// control[5]: overflow <= 0;
// control[6]: result <= MAXIMUM;
// control[7]: overflow <= 1;
// control[8]: result <= MINIMUM;
// control[9]: overflow <= 1;
// control[10]: result <= (H == 0)? total : next_total;
// control[11]: total <= next_total;
// control[12]: harmonic <= harmonic + 1;

// ---------------- CONTROLLER ----------------
module fourier_series_controller #
(
  parameter W = 32,
  parameter Q = 20,
  parameter H = 3
)
(
  input clk,
  input rst_n,
  input start,
  input [2:0] status,
  output reg [12:0] control,
  output reg busy,
  output reg done);
localparam signed [63:0] MAXIMUM = (64'sd1 << W - 1) - 1;
localparam signed [63:0] MINIMUM = -(64'sd1 << W - 1);

reg next_busy;
reg next_done;

// FSM state/handshake registers; all data writes are control strobes.

always @(posedge clk) if(!rst_n) begin
  busy <= 0;
  done <= 0;
end else begin
  busy <= next_busy;
  done <= next_done;
end


always @(*) begin
  next_busy = busy;
  next_done = done;
  control = 0;
  begin
    next_done = 0;
    if(start && !busy) begin
      control[0] = 1'b1;
      control[1] = 1'b1;
      control[2] = 1'b1;
      control[3] = 1'b1;
      control[4] = 1'b1;
      next_busy = 1;
      control[5] = 1'b1;
    end else if(busy) begin
      if((H == 0) || status[0]) begin
        if(status[1]) begin
          control[6] = 1'b1;
          control[7] = 1'b1;
        end else if(status[2]) begin
          control[8] = 1'b1;
          control[9] = 1'b1;
        end else control[10] = 1'b1;
        next_busy = 0;
        next_done = 1;
      end else begin
        control[11] = 1'b1;
        control[12] = 1'b1;
      end
    end
  end
end

endmodule

// ---------------- DATAPATH ----------------
module fourier_series_datapath #
(
  parameter W = 32,
  parameter Q = 20,
  parameter H = 3
)
(
  input clk,
  input rst_n,
  input [5:0] phase,
  input [(H+1)*W-1:0] cosine_coefficients,
  input [(H+1)*W-1:0] sine_coefficients,
  input [12:0] control,
  output [2:0] status,
  output reg signed [W-1:0] result,
  output reg overflow);
localparam signed [63:0] MAXIMUM = (64'sd1 << W - 1) - 1;
localparam signed [63:0] MINIMUM = -(64'sd1 << W - 1);
reg [(H+1)*W-1:0] c;
reg [(H+1)*W-1:0] s;
reg [5:0] saved_phase;
integer harmonic;
reg signed [63:0] total;
reg signed [63:0] next_total;
reg signed [127:0] product;
wire [5:0] angle;
assign angle = saved_phase * harmonic;
wire signed [W-1:0] cosine;
wire signed [W-1:0] negative_sine;
wire signed [W-1:0] ch;
assign ch = c[(((harmonic <= H)? harmonic : 0) * W) +: W];
wire signed [W-1:0] sh;
assign sh = s[(((harmonic <= H)? harmonic : 0) * W) +: W];

fourier_series_helper_twiddle_rom
#(
  W,
  Q
)
table_rom
(
  angle,
  cosine,
  negative_sine
);


always @(*) begin
  product = $signed(ch) * $signed(cosine) - $signed(sh) * $signed(negative_sine);
  next_total = total + (product >>> Q);
end


// Status predicates are generated by the datapath, never by the FSM.
assign status[0] = (harmonic == H);
assign status[1] = (((H == 0)? total : next_total) > MAXIMUM);
assign status[2] = (((H == 0)? total : next_total) < MINIMUM);

// Register-transfer operations. Later strobes retain nonblocking
// assignment priority when the same destination is written twice.

always @(posedge clk) if(!rst_n) begin
  c <= 0;
  s <= 0;
  saved_phase <= 0;
  harmonic <= 1;
  total <= 0;
  result <= 0;
  overflow <= 0;
end else begin
  if(control[0]) begin
    c <= cosine_coefficients;
  end
  if(control[1]) begin
    s <= sine_coefficients;
  end
  if(control[2]) begin
    saved_phase <= phase;
  end
  if(control[3]) begin
    harmonic <= 1;
  end
  if(control[4]) begin
    total <= $signed(cosine_coefficients[0 +: W]);
  end
  if(control[5]) begin
    overflow <= 0;
  end
  if(control[6]) begin
    result <= MAXIMUM;
  end
  if(control[7]) begin
    overflow <= 1;
  end
  if(control[8]) begin
    result <= MINIMUM;
  end
  if(control[9]) begin
    overflow <= 1;
  end
  if(control[10]) begin
    result <= (H == 0)? total : next_total;
  end
  if(control[11]) begin
    total <= next_total;
  end
  if(control[12]) begin
    harmonic <= harmonic + 1;
  end
end

endmodule

// ---------------- TOP ----------------
module fourier_series #
(
  parameter W = 32,
  parameter Q = 20,
  parameter H = 3
)
(
  input clk,
  input rst_n,
  input start,
  input [5:0] phase,
  input [(H+1)*W-1:0] cosine_coefficients,
  input [(H+1)*W-1:0] sine_coefficients,
  output signed [W-1:0] result,
  output busy,
  output done,
  output overflow);
wire [12:0] control;
wire [2:0] status;
fourier_series_controller #(.W(W), .Q(Q), .H(H)) controller (
    .clk(clk),
    .rst_n(rst_n),
    .start(start),
    .status(status),
    .control(control),
    .busy(busy),
    .done(done)
);
fourier_series_datapath #(.W(W), .Q(Q), .H(H)) datapath (
    .clk(clk),
    .rst_n(rst_n),
    .phase(phase),
    .cosine_coefficients(cosine_coefficients),
    .sine_coefficients(sine_coefficients),
    .control(control),
    .status(status),
    .result(result),
    .overflow(overflow)
);
endmodule


