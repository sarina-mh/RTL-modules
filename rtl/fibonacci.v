// F(0)=0,F(1)=1. Unsigned result wraps modulo 2**W; overflow is sticky.

// =====================================================================
// fibonacci: complete controller + datapath + top in one Verilog file.
// Pulse start while busy=0. Inputs are latched on the accepting edge.
// Reset and port conventions are preserved from the original module.
// Packed array lane i occupies bits [i*W +: W], unless stated otherwise.
// =====================================================================
// control[0]: a <= 0;
// control[1]: b <= 1;
// control[2]: limit <= n;
// control[3]: p <= 0;
// control[4]: overflow <= 0;
// control[5]: result <= a;
// control[6]: a <= b;
// control[7]: b <= sum[W-1:0];
// control[8]: p <= p + 1'b1;
// control[9]: overflow <= 1;

// ---------------- CONTROLLER ----------------
module fibonacci_controller #
(
  parameter W = 32,
  parameter B = 8
)
(
  input clk,
  input rst_n,
  input start,
  input [2:0] status,
  output reg [9:0] control,
  output reg busy,
  output reg done);


reg next_busy;
reg next_done;

// FSM state/handshake registers; all data writes are control strobes.

always @(posedge clk) if(!rst_n) begin
  busy <= 0;
  done <= 0;
end else begin
  busy <= next_busy;
  done <= next_done;
end


always @(*) begin
  next_busy = busy;
  next_done = done;
  control = 0;
  begin
    next_done = 0;
    if(start && !busy) begin
      control[0] = 1'b1;
      control[1] = 1'b1;
      control[2] = 1'b1;
      control[3] = 1'b1;
      next_busy = 1;
      control[4] = 1'b1;
    end else if(busy) begin
      if(status[0]) begin
        control[5] = 1'b1;
        next_busy = 0;
        next_done = 1;
      end else begin
        control[6] = 1'b1;
        control[7] = 1'b1;
        control[8] = 1'b1;
        if(status[1] && status[2]) control[9] = 1'b1;
      end
    end
  end
end

endmodule

// ---------------- DATAPATH ----------------
module fibonacci_datapath #
(
  parameter W = 32,
  parameter B = 8
)
(
  input clk,
  input rst_n,
  input [B-1:0] n,
  input [9:0] control,
  output [2:0] status,
  output reg [W-1:0] result,
  output reg overflow);
reg [W-1:0] a;
reg [W-1:0] b;
reg [B-1:0] limit;
reg [B-1:0] p;
wire [W:0] sum;
assign sum = { 1'b0, a } + { 1'b0, b };

// Status predicates are generated by the datapath, never by the FSM.
assign status[0] = (p == limit);
assign status[1] = sum[W];
assign status[2] = (p + 1 < limit);

// Register-transfer operations. Later strobes retain nonblocking
// assignment priority when the same destination is written twice.

always @(posedge clk) if(!rst_n) begin
  result <= 0;
  overflow <= 0;
  a <= 0;
  b <= 1;
  limit <= 0;
  p <= 0;
end else begin
  if(control[0]) begin
    a <= 0;
  end
  if(control[1]) begin
    b <= 1;
  end
  if(control[2]) begin
    limit <= n;
  end
  if(control[3]) begin
    p <= 0;
  end
  if(control[4]) begin
    overflow <= 0;
  end
  if(control[5]) begin
    result <= a;
  end
  if(control[6]) begin
    a <= b;
  end
  if(control[7]) begin
    b <= sum[W-1:0];
  end
  if(control[8]) begin
    p <= p + 1'b1;
  end
  if(control[9]) begin
    overflow <= 1;
  end
end

endmodule

// ---------------- TOP ----------------
module fibonacci #
(
  parameter W = 32,
  parameter B = 8
)
(
  input clk,
  input rst_n,
  input start,
  input [B-1:0] n,
  output [W-1:0] result,
  output busy,
  output done,
  output overflow);
wire [9:0] control;
wire [2:0] status;
fibonacci_controller #(.W(W), .B(B)) controller (
    .clk(clk),
    .rst_n(rst_n),
    .start(start),
    .status(status),
    .control(control),
    .busy(busy),
    .done(done)
);
fibonacci_datapath #(.W(W), .B(B)) datapath (
    .clk(clk),
    .rst_n(rst_n),
    .n(n),
    .control(control),
    .status(status),
    .result(result),
    .overflow(overflow)
);
endmodule
