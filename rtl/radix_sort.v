// Stable binary LSD radix sort. Each pass scatters zeros then ones.
// No exponential histogram; signed ordering flips the sign bit in the last pass.

// =====================================================================
// radix_sort: complete controller + datapath + top in one Verilog file.
// Pulse start while busy=0. Inputs are latched on the accepting edge.
// Reset and port conventions are preserved from the original module.
// Packed array lane i occupies bits [i*W +: W], unless stated otherwise.
// =====================================================================
// control[0]: for(k=0; k<N; k=k+1) mem[k] <= data_in[(k * W) +: W];
// control[1]: bit_index <= 0;
// control[2]: p <= 0;
// control[3]: out_index <= 0;
// control[4]: temp[out_index] <= mem[p];
// control[5]: out_index <= out_index + 1;
// control[6]: p <= 0;
// control[7]: p <= p + 1;
// control[8]: temp[out_index] <= mem[p];
// control[9]: out_index <= out_index + 1;
// control[10]: p <= 0;
// control[11]: p <= p + 1;
// control[12]: mem[p] <= temp[p];
// control[13]: p <= 0;
// control[14]: out_index <= 0;
// control[15]: bit_index <= bit_index + 1;
// control[16]: p <= p + 1;
// control[17]: for(k=0; k<N; k=k+1) data_out[(k * W) +: W] <= mem[k];

// ---------------- CONTROLLER ----------------
module radix_sort_controller #
(
  parameter W = 8,
  parameter N = 8,
  parameter SIGNED = 0
)
(
  input clk,
  input rst_n,
  input start,
  input [3:0] status,
  output reg [17:0] control,
  output reg busy,
  output reg done);

reg [2:0] state;
reg next_busy;
reg next_done;
reg [2:0] next_state;

// FSM state/handshake registers; all data writes are control strobes.

always @(posedge clk) if(!rst_n) begin
  busy <= 0;
  done <= 0;
  state <= 0;
end else begin
  busy <= next_busy;
  done <= next_done;
  state <= next_state;
end


always @(*) begin
  next_busy = busy;
  next_done = done;
  next_state = state;
  control = 0;
  begin
    next_done = 0;
    if(start && !busy) begin
      control[0] = 1'b1;
      control[1] = 1'b1;
      control[2] = 1'b1;
      control[3] = 1'b1;
      next_state = 0;
      next_busy = 1;
    end else if(busy) case(state)
      0: begin
        if(status[0]) begin
          control[4] = 1'b1;
          control[5] = 1'b1;
        end
        if(status[1]) begin
          control[6] = 1'b1;
          next_state = 1;
        end else control[7] = 1'b1;
      end
      1: begin
        if(status[2]) begin
          control[8] = 1'b1;
          control[9] = 1'b1;
        end
        if(status[1]) begin
          control[10] = 1'b1;
          next_state = 2;
        end else control[11] = 1'b1;
      end
      2: begin
        control[12] = 1'b1;
        if(status[1]) begin
          control[13] = 1'b1;
          control[14] = 1'b1;
          if(status[3]) next_state = 3;
          else begin
            control[15] = 1'b1;
            next_state = 0;
          end
        end else control[16] = 1'b1;
      end
      3: begin
        control[17] = 1'b1;
        next_busy = 0;
        next_done = 1;
      end
      default: next_state = 0;
    endcase
  end
end

endmodule

// ---------------- DATAPATH ----------------
module radix_sort_datapath #
(
  parameter W = 8,
  parameter N = 8,
  parameter SIGNED = 0
)
(
  input clk,
  input rst_n,
  input [N*W-1:0] data_in,
  input [17:0] control,
  output [3:0] status,
  output reg [N*W-1:0] data_out);
reg [W-1:0] mem [0:N-1];
reg [W-1:0] temp [0:N-1];
integer bit_index;
integer p;
integer out_index;
integer k;
wire digit;
assign digit = mem[p][bit_index] ^ (SIGNED && (bit_index == W - 1));

// Status predicates are generated by the datapath, never by the FSM.
assign status[0] = (!digit);
assign status[1] = (p == N - 1);
assign status[2] = digit;
assign status[3] = (bit_index == W - 1);

// Register-transfer operations. Later strobes retain nonblocking
// assignment priority when the same destination is written twice.

always @(posedge clk) if(!rst_n) begin
  data_out <= 0;
  bit_index <= 0;
  p <= 0;
  out_index <= 0;
  for(k=0; k<N; k=k+1) begin
    mem[k] <= 0;
    temp[k] <= 0;
  end
end else begin
  if(control[0]) begin
    for(k=0; k<N; k=k+1) mem[k] <= data_in[(k * W) +: W];
  end
  if(control[1]) begin
    bit_index <= 0;
  end
  if(control[2]) begin
    p <= 0;
  end
  if(control[3]) begin
    out_index <= 0;
  end
  if(control[4]) begin
    temp[out_index] <= mem[p];
  end
  if(control[5]) begin
    out_index <= out_index + 1;
  end
  if(control[6]) begin
    p <= 0;
  end
  if(control[7]) begin
    p <= p + 1;
  end
  if(control[8]) begin
    temp[out_index] <= mem[p];
  end
  if(control[9]) begin
    out_index <= out_index + 1;
  end
  if(control[10]) begin
    p <= 0;
  end
  if(control[11]) begin
    p <= p + 1;
  end
  if(control[12]) begin
    mem[p] <= temp[p];
  end
  if(control[13]) begin
    p <= 0;
  end
  if(control[14]) begin
    out_index <= 0;
  end
  if(control[15]) begin
    bit_index <= bit_index + 1;
  end
  if(control[16]) begin
    p <= p + 1;
  end
  if(control[17]) begin
    for(k=0; k<N; k=k+1) data_out[(k * W) +: W] <= mem[k];
  end
end

endmodule

// ---------------- TOP ----------------
module radix_sort #
(
  parameter W = 8,
  parameter N = 8,
  parameter SIGNED = 0
)
(
  input clk,
  input rst_n,
  input start,
  input [N*W-1:0] data_in,
  output [N*W-1:0] data_out,
  output busy,
  output done);
wire [17:0] control;
wire [3:0] status;
radix_sort_controller #(.W(W), .N(N), .SIGNED(SIGNED)) controller (
    .clk(clk),
    .rst_n(rst_n),
    .start(start),
    .status(status),
    .control(control),
    .busy(busy),
    .done(done)
);
radix_sort_datapath #(.W(W), .N(N), .SIGNED(SIGNED)) datapath (
    .clk(clk),
    .rst_n(rst_n),
    .data_in(data_in),
    .control(control),
    .status(status),
    .data_out(data_out)
);
endmodule
