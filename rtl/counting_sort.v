// Counting sort for SMALL integer keys (1 <= W <= 10 recommended).
// Histogram storage grows as 2**W. Signed order uses sign-bit biased keys.

// =====================================================================
// counting_sort: complete controller + datapath + top in one Verilog file.
// Pulse start while busy=0. Inputs are latched on the accepting edge.
// Reset and port conventions are preserved from the original module.
// Packed array lane i occupies bits [i*W +: W], unless stated otherwise.
// =====================================================================
// control[0]: data <= data_in;
// control[1]: p <= 0;
// control[2]: key <= 0;
// control[3]: out_index <= 0;
// control[4]: histogram[key] <= 0;
// control[5]: key <= 0;
// control[6]: key <= key + 1;
// control[7]: histogram[current] <= histogram[current] + 1;
// control[8]: p <= p + 1;
// control[9]: data_out[(out_index * W) +: W] <= key ^ bias;
// control[10]: histogram[key] <= histogram[key] - 1;
// control[11]: out_index <= out_index + 1;
// control[12]: key <= key + 1;

// ---------------- CONTROLLER ----------------
module counting_sort_controller #
(
  parameter W = 4,
  parameter N = 8,
  parameter SIGNED = 0
)
(
  input clk,
  input rst_n,
  input start,
  input [3:0] status,
  output reg [12:0] control,
  output reg busy,
  output reg done);
localparam RANGE = 1 << W;
reg [1:0] state;
reg next_busy;
reg next_done;
reg [1:0] next_state;

// FSM state/handshake registers; all data writes are control strobes.

always @(posedge clk) if(!rst_n) begin
  busy <= 0;
  done <= 0;
  state <= 0;
end else begin
  busy <= next_busy;
  done <= next_done;
  state <= next_state;
end


always @(*) begin
  next_busy = busy;
  next_done = done;
  next_state = state;
  control = 0;
  begin
    next_done = 0;
    if(start && !busy) begin
      control[0] = 1'b1;
      control[1] = 1'b1;
      control[2] = 1'b1;
      control[3] = 1'b1;
      next_busy = 1;
      next_state = 0;
    end else if(busy) case(state)
      0: begin
        control[4] = 1'b1;
        if(status[0]) begin
          control[5] = 1'b1;
          next_state = 1;
        end else control[6] = 1'b1;
      end
      1: begin
        control[7] = 1'b1;
        if(status[1]) next_state = 2;
        else control[8] = 1'b1;
      end
      2: if(status[2]) begin
        control[9] = 1'b1;
        control[10] = 1'b1;
        control[11] = 1'b1;
        if(status[3]) next_state = 3;
      end else control[12] = 1'b1;
      3: begin
        next_busy = 0;
        next_done = 1;
      end
    endcase
  end
end

endmodule

// ---------------- DATAPATH ----------------
module counting_sort_datapath #
(
  parameter W = 4,
  parameter N = 8,
  parameter SIGNED = 0
)
(
  input clk,
  input rst_n,
  input [N*W-1:0] data_in,
  input [12:0] control,
  output [3:0] status,
  output reg [N*W-1:0] data_out);
localparam RANGE = 1 << W;
reg [N*W-1:0] data;
reg signed [31:0] histogram [0:RANGE-1];
integer p;
integer key;
integer out_index;
integer k;
wire [W-1:0] bias;
assign bias = (SIGNED)? 1 << W - 1 : 0;
wire [W-1:0] current;
assign current = data[(p * W) +: W] ^ bias;

// Status predicates are generated by the datapath, never by the FSM.
assign status[0] = (key == RANGE - 1);
assign status[1] = (p == N - 1);
assign status[2] = (histogram[key] > 0);
assign status[3] = (out_index == N - 1);

// Register-transfer operations. Later strobes retain nonblocking
// assignment priority when the same destination is written twice.

always @(posedge clk) if(!rst_n) begin
  data_out <= 0;
  data <= 0;
  p <= 0;
  key <= 0;
  out_index <= 0;
end else begin
  if(control[0]) begin
    data <= data_in;
  end
  if(control[1]) begin
    p <= 0;
  end
  if(control[2]) begin
    key <= 0;
  end
  if(control[3]) begin
    out_index <= 0;
  end
  if(control[4]) begin
    histogram[key] <= 0;
  end
  if(control[5]) begin
    key <= 0;
  end
  if(control[6]) begin
    key <= key + 1;
  end
  if(control[7]) begin
    histogram[current] <= histogram[current] + 1;
  end
  if(control[8]) begin
    p <= p + 1;
  end
  if(control[9]) begin
    data_out[(out_index * W) +: W] <= key ^ bias;
  end
  if(control[10]) begin
    histogram[key] <= histogram[key] - 1;
  end
  if(control[11]) begin
    out_index <= out_index + 1;
  end
  if(control[12]) begin
    key <= key + 1;
  end
end

endmodule

// ---------------- TOP ----------------
module counting_sort #
(
  parameter W = 4,
  parameter N = 8,
  parameter SIGNED = 0
)
(
  input clk,
  input rst_n,
  input start,
  input [N*W-1:0] data_in,
  output [N*W-1:0] data_out,
  output busy,
  output done);
wire [12:0] control;
wire [3:0] status;
counting_sort_controller #(.W(W), .N(N), .SIGNED(SIGNED)) controller (
    .clk(clk),
    .rst_n(rst_n),
    .start(start),
    .status(status),
    .control(control),
    .busy(busy),
    .done(done)
);
counting_sort_datapath #(.W(W), .N(N), .SIGNED(SIGNED)) datapath (
    .clk(clk),
    .rst_n(rst_n),
    .data_in(data_in),
    .control(control),
    .status(status),
    .data_out(data_out)
);
endmodule
