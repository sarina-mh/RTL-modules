// Stable bottom-up merge sort. One merge output or copy-back per cycle.

// =====================================================================
// merge_sort: complete controller + datapath + top in one Verilog file.
// Pulse start while busy=0. Inputs are latched on the accepting edge.
// Reset and port conventions are preserved from the original module.
// Packed array lane i occupies bits [i*W +: W], unless stated otherwise.
// =====================================================================
// control[0]: for(k=0; k<N; k=k+1) mem[k] <= data_in[(k * W) +: W];
// control[1]: width <= 1;
// control[2]: left <= 0;
// control[3]: middle <= (left + width < N)? left + width : N;
// control[4]: limit <= (left + 2 * width < N)? left + 2 * width : N;
// control[5]: i <= left;
// control[6]: j <= (left + width < N)? left + width : N;
// control[7]: p <= left;
// control[8]: p <= left;
// control[9]: temp[p] <= mem[i];
// control[10]: i <= i + 1;
// control[11]: temp[p] <= mem[j];
// control[12]: j <= j + 1;
// control[13]: p <= p + 1;
// control[14]: mem[p] <= temp[p];
// control[15]: p <= p + 1;
// control[16]: left <= limit;
// control[17]: width <= width * 2;
// control[18]: left <= 0;
// control[19]: for(k=0; k<N; k=k+1) data_out[(k * W) +: W] <= mem[k];

// ---------------- CONTROLLER ----------------
module merge_sort_controller #
(
  parameter W = 8,
  parameter N = 8,
  parameter SIGNED = 0
)
(
  input clk,
  input rst_n,
  input start,
  input [6:0] status,
  output reg [19:0] control,
  output reg busy,
  output reg done);

reg [2:0] state;
reg next_busy;
reg next_done;
reg [2:0] next_state;

// FSM state/handshake registers; all data writes are control strobes.

always @(posedge clk) if(!rst_n) begin
  busy <= 0;
  done <= 0;
  state <= 0;
end else begin
  busy <= next_busy;
  done <= next_done;
  state <= next_state;
end


always @(*) begin
  next_busy = busy;
  next_done = done;
  next_state = state;
  control = 0;
  begin
    next_done = 0;
    if(start && !busy) begin
      control[0] = 1'b1;
      control[1] = 1'b1;
      control[2] = 1'b1;
      next_state = (N == 1)? 4 : 0;
      next_busy = 1;
    end else if(busy) case(state)
      0: begin
        control[3] = 1'b1;
        control[4] = 1'b1;
        control[5] = 1'b1;
        control[6] = 1'b1;
        control[7] = 1'b1;
        next_state = 1;
      end
      1: begin
        if(status[0]) begin
          control[8] = 1'b1;
          next_state = 2;
        end else begin
          if(status[1] && (status[2] || status[3])) begin
            control[9] = 1'b1;
            control[10] = 1'b1;
          end else begin
            control[11] = 1'b1;
            control[12] = 1'b1;
          end
          control[13] = 1'b1;
        end
      end
      2: begin
        control[14] = 1'b1;
        if(status[4]) next_state = 3;
        else control[15] = 1'b1;
      end
      3: if(status[5]) begin
        control[16] = 1'b1;
        next_state = 0;
      end else if(status[6]) next_state = 4;
      else begin
        control[17] = 1'b1;
        control[18] = 1'b1;
        next_state = 0;
      end
      4: begin
        control[19] = 1'b1;
        next_busy = 0;
        next_done = 1;
      end
      default: next_state = 0;
    endcase
  end
end

endmodule

// ---------------- DATAPATH ----------------
module merge_sort_datapath #
(
  parameter W = 8,
  parameter N = 8,
  parameter SIGNED = 0
)
(
  input clk,
  input rst_n,
  input [N*W-1:0] data_in,
  input [19:0] control,
  output [6:0] status,
  output reg [N*W-1:0] data_out);
reg [W-1:0] mem [0:N-1];
reg [W-1:0] temp [0:N-1];
integer width;
integer left;
integer middle;
integer limit;
integer i;
integer j;
integer p;
integer k;
wire le;
assign le = (SIGNED)? $signed(mem[i]) <= $signed(mem[j]) : mem[i] <= mem[j];

// Status predicates are generated by the datapath, never by the FSM.
assign status[0] = (p == limit);
assign status[1] = (i < middle);
assign status[2] = (j >= limit);
assign status[3] = le;
assign status[4] = (p == limit - 1);
assign status[5] = (limit < N);
assign status[6] = (2 * width >= N);

// Register-transfer operations. Later strobes retain nonblocking
// assignment priority when the same destination is written twice.

always @(posedge clk) if(!rst_n) begin
  data_out <= 0;
  width <= 1;
  left <= 0;
  middle <= 0;
  limit <= 0;
  i <= 0;
  j <= 0;
  p <= 0;
  for(k=0; k<N; k=k+1) begin
    mem[k] <= 0;
    temp[k] <= 0;
  end
end else begin
  if(control[0]) begin
    for(k=0; k<N; k=k+1) mem[k] <= data_in[(k * W) +: W];
  end
  if(control[1]) begin
    width <= 1;
  end
  if(control[2]) begin
    left <= 0;
  end
  if(control[3]) begin
    middle <= (left + width < N)? left + width : N;
  end
  if(control[4]) begin
    limit <= (left + 2 * width < N)? left + 2 * width : N;
  end
  if(control[5]) begin
    i <= left;
  end
  if(control[6]) begin
    j <= (left + width < N)? left + width : N;
  end
  if(control[7]) begin
    p <= left;
  end
  if(control[8]) begin
    p <= left;
  end
  if(control[9]) begin
    temp[p] <= mem[i];
  end
  if(control[10]) begin
    i <= i + 1;
  end
  if(control[11]) begin
    temp[p] <= mem[j];
  end
  if(control[12]) begin
    j <= j + 1;
  end
  if(control[13]) begin
    p <= p + 1;
  end
  if(control[14]) begin
    mem[p] <= temp[p];
  end
  if(control[15]) begin
    p <= p + 1;
  end
  if(control[16]) begin
    left <= limit;
  end
  if(control[17]) begin
    width <= width * 2;
  end
  if(control[18]) begin
    left <= 0;
  end
  if(control[19]) begin
    for(k=0; k<N; k=k+1) data_out[(k * W) +: W] <= mem[k];
  end
end

endmodule

// ---------------- TOP ----------------
module merge_sort #
(
  parameter W = 8,
  parameter N = 8,
  parameter SIGNED = 0
)
(
  input clk,
  input rst_n,
  input start,
  input [N*W-1:0] data_in,
  output [N*W-1:0] data_out,
  output busy,
  output done);
wire [19:0] control;
wire [6:0] status;
merge_sort_controller #(.W(W), .N(N), .SIGNED(SIGNED)) controller (
    .clk(clk),
    .rst_n(rst_n),
    .start(start),
    .status(status),
    .control(control),
    .busy(busy),
    .done(done)
);
merge_sort_datapath #(.W(W), .N(N), .SIGNED(SIGNED)) datapath (
    .clk(clk),
    .rst_n(rst_n),
    .data_in(data_in),
    .control(control),
    .status(status),
    .data_out(data_out)
);
endmodule
